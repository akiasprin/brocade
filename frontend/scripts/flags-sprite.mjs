// Regenerate the bundled vector flag sheet: cd frontend && node scripts/flags-sprite.mjs [tarball]
// flag-icons 7.5.0 is pinned below; jsdom already belongs to the frontend development toolchain.
// Runtime uses one local sheet, so country codes never become requests to a third-party CDN.
// Keep SVG paths rather than flattening 48×32 cells to pixels: large identity marks and high-DPI
// displays need the original detail. Each 4:3 source is center-cropped into the existing 3:2 cell.
import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { mkdtempSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { JSDOM } from 'jsdom';
import { chromium } from 'playwright';

const VERSION = '7.5.0';
const INTEGRITY = 'kd+MNXviFIg5hijH766tt+3x76ele1AXlo4zDdCxIvqWZhKt4T83bOtxUOOMlTx/EcFdUMH5yvQgYlFh1EqqFg==';
const CELL_W = 48;
const CELL_H = 32;
const COLS = 16;
const SVG_NS = 'http://www.w3.org/2000/svg';
const MAX_ARCHIVE_BYTES = 16 * 1024 * 1024;
const ui = join(dirname(fileURLToPath(import.meta.url)), '..', 'src', 'ui');
/** Inline 6×4 cells paint before the external vector sheet has arrived. */
async function writePreview(svg) {
  const rows = Math.ceil(flagCount(svg) / COLS);
  const browser = await chromium.launch();
  try {
    const page = await browser.newPage({ viewport: { width: COLS * 6, height: rows * 4 }, deviceScaleFactor: 1 });
    await page.setContent(
      `<style>body{margin:0}img{display:block;width:100%;height:100vh}</style><img src="data:image/svg+xml;base64,${Buffer.from(svg).toString('base64')}">`,
    );
    await page.locator('img').evaluate(image => image.decode());
    const pixels = await page.locator('img').screenshot({ type: 'png', omitBackground: true });
    const digest = createHash('sha256').update(svg).digest('hex');
    writeFileSync(
      join(ui, 'flags-preview.css'),
      `/* Generated by flags-sprite.mjs; flag-icons ${VERSION} license: flags.svg. Source SHA-256: ${digest} */\n:root { --flag-preview: url('data:image/png;base64,${pixels.toString('base64')}'); }\n`,
    );
    console.log(`flags-preview: ${pixels.length} bytes, ${COLS * 6}×${rows * 4}`);
  } finally {
    await browser.close();
  }
}
function flagCount(svg) {
  const document = new JSDOM(svg, { contentType: 'image/svg+xml' });
  try {
    return document.window.document.documentElement.querySelectorAll(':scope > svg').length;
  } finally {
    document.window.close();
  }
}
if (process.argv[2] === '--preview-only') {
  await writePreview(readFileSync(join(ui, 'flags.svg'), 'utf8'));
} else {
  const work = mkdtempSync(join(tmpdir(), 'brocade-flags-'));
  const window = new JSDOM('').window;
  try {
    let archive;
    if (process.argv[2]) {
      if (statSync(process.argv[2]).size > MAX_ARCHIVE_BYTES) throw new Error('flag-icons archive is too large');
      archive = readFileSync(process.argv[2]);
    } else {
      const response = await fetch(`https://registry.npmjs.org/flag-icons/-/flag-icons-${VERSION}.tgz`, {
        signal: AbortSignal.timeout(30_000),
      });
      if (!response.ok) throw new Error(`flag-icons download: HTTP ${response.status}`);
      const chunks = [];
      let bytes = 0;
      for await (const chunk of response.body) {
        bytes += chunk.length;
        if (bytes > MAX_ARCHIVE_BYTES) throw new Error('flag-icons archive is too large');
        chunks.push(chunk);
      }
      archive = Buffer.concat(chunks);
    }
    if (archive.length > MAX_ARCHIVE_BYTES || createHash('sha512').update(archive).digest('base64') !== INTEGRITY)
      throw new Error('flag-icons archive does not match the pinned 7.5.0 integrity');
    const tarball = join(work, 'flag-icons.tgz');
    writeFileSync(tarball, archive);
    execFileSync('tar', ['xzf', tarball, '-C', work]);
    const svgDir = join(work, 'package', 'flags', '4x3');
    const codes = readdirSync(svgDir)
      .filter(name => /^[a-z]{2}\.svg$/.test(name))
      .map(name => name.slice(0, 2))
      .sort();
    const rows = Math.ceil(codes.length / COLS);
    const document = window.document.implementation.createDocument(SVG_NS, 'svg');
    const sheet = document.documentElement;
    sheet.setAttribute('width', String(COLS * CELL_W));
    sheet.setAttribute('height', String(rows * CELL_H));
    sheet.setAttribute('viewBox', `0 0 ${COLS * CELL_W} ${rows * CELL_H}`);
    // CSS scales the sheet to the flag box in both axes (for example 16×11). Root letterboxing
    // would shift every row relative to the percentage sprite coordinates. Each child keeps its crop.
    sheet.setAttribute('preserveAspectRatio', 'none');
    // Retain the upstream license in the actual distributed asset.
    sheet.append(
      document.createComment(
        ` Generated from flag-icons ${VERSION}.\n${readFileSync(join(work, 'package', 'LICENSE'), 'utf8')} `,
      ),
    );
    const parser = new window.DOMParser();
    for (const [index, code] of codes.entries()) {
      const parsed = parser.parseFromString(readFileSync(join(svgDir, `${code}.svg`), 'utf8'), 'image/svg+xml');
      if (
        parsed.querySelector('parsererror,script,foreignObject,image,style') ||
        parsed.documentElement.namespaceURI !== SVG_NS
      )
        throw new Error(`Unsupported source SVG: ${code}`);
      const flag = document.importNode(parsed.documentElement, true);
      const ids = new Map(
        [...flag.querySelectorAll('[id]'), flag].filter(e => e.id).map(e => [e.id, `${code}-${e.id}`]),
      );
      const reference = id => {
        if (!ids.has(id)) throw new Error(`Unknown SVG reference in ${code}: ${id}`);
        return ids.get(id);
      };
      for (const element of [flag, ...flag.querySelectorAll('*')]) {
        for (const attribute of [...element.attributes]) {
          if (/^on/i.test(attribute.localName)) throw new Error(`Unexpected event attribute: ${code}`);
          let value = attribute.value;
          if (attribute.localName === 'id') value = reference(value);
          else if (attribute.localName === 'href') {
            if (!value.startsWith('#')) throw new Error(`External SVG reference: ${code}`);
            value = `#${reference(value.slice(1))}`;
          } else value = value.replace(/url\(\s*['"]?#([^)'"\s]+)['"]?\s*\)/g, (_, id) => `url(#${reference(id)})`);
          attribute.value = value;
        }
      }
      flag.setAttribute('x', String((index % COLS) * CELL_W));
      flag.setAttribute('y', String(Math.floor(index / COLS) * CELL_H));
      flag.setAttribute('width', String(CELL_W));
      flag.setAttribute('height', String(CELL_H));
      flag.setAttribute('preserveAspectRatio', 'xMidYMid slice');
      flag.setAttribute('overflow', 'hidden');
      sheet.append(flag);
    }
    const svg = new window.XMLSerializer().serializeToString(document);
    writeFileSync(join(ui, 'flags.svg'), svg + '\n');
    await writePreview(svg + '\n');
    const lines = Array.from({ length: rows }, (_, row) => codes.slice(row * COLS, (row + 1) * COLS).join(''));
    writeFileSync(
      join(ui, 'flags.ts'),
      [
        '// 由 frontend/scripts/flags-sprite.mjs 生成，别手改（改了下次生成也会被覆盖）。',
        '',
        '/** 矢量旗帜表的列数，逻辑格子为 48×32（3:2），实际清晰度随显示尺寸缩放。 */',
        `export const FLAG_COLS = ${COLS};`,
        '',
        '/** 每行对应旗帜表的一行，每两个字符为一个 ISO 3166-1 alpha-2 地区码。 */',
        'export const FLAG_SHEET = [',
        ...lines.map(line => `  '${line}',`),
        '];',
        '',
      ].join('\n'),
    );
    rmSync(join(ui, 'flags.png'), { force: true });
    console.log(
      `flags.svg: ${codes.length} vector flags, ${COLS}×${rows} cells, ${(Buffer.byteLength(svg) / 1024).toFixed(1)} KiB`,
    );
  } finally {
    window.close();
    rmSync(work, { recursive: true, force: true });
  }
}
