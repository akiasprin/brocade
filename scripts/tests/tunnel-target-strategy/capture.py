"""Decode the destination received by a loopback TLS AnyTLS peer.

The Rust integration test supplies real compiler-generated configurations and the
Console's embedded Xray. This peer never connects to the requested destination.
"""

import argparse
import hashlib
import ipaddress
import json
import queue
import socket
import ssl
import struct
import subprocess
import threading
import time
from pathlib import Path


def read_exact(stream, length):
    data = bytearray()
    while len(data) < length:
        block = stream.recv(length - len(data))
        if not block:
            raise EOFError("connection ended before the expected bytes")
        data.extend(block)
    return bytes(data)


def read_address(data):
    address_type = data[0]
    if address_type == 1:
        end = 5
        address = str(ipaddress.IPv4Address(data[1:end]))
    elif address_type == 4:
        end = 17
        address = str(ipaddress.IPv6Address(data[1:end]))
    elif address_type == 3:
        end = 2 + data[1]
        address = data[2:end].decode("ascii")
    else:
        raise AssertionError(f"unknown destination address type {address_type}")
    assert len(data) == end + 2, "unexpected bytes in the address frame"
    return {
        "address_type": address_type,
        "address": address,
        "port": struct.unpack("!H", data[end:])[0],
        "address_hex": data.hex(),
    }


def capture_destination(listener, context, credential, result, release):
    try:
        listener.settimeout(5)
        connection, _ = listener.accept()
        connection.settimeout(5)
        with context.wrap_socket(connection, server_side=True) as stream:
            authentication = read_exact(stream, 34)
            assert authentication[:32] == hashlib.sha256(credential.encode()).digest()
            padding = struct.unpack("!H", authentication[32:])[0]
            read_exact(stream, padding)
            opened = set()
            for _ in range(64):
                command, stream_id, length = struct.unpack("!BIH", read_exact(stream, 7))
                payload = read_exact(stream, length)
                if command == 1:
                    assert length == 0
                    opened.add(stream_id)
                elif command == 2 and stream_id in opened:
                    destination = read_address(payload)
                    destination["stream_id"] = stream_id
                    result.put(destination)
                    release.wait(5)
                    return
            raise AssertionError("no AnyTLS stream destination was received")
    except Exception as error:
        result.put(error)


def socks_connect(port, destination):
    stream = socket.create_connection(("127.0.0.1", port), timeout=5)
    stream.settimeout(5)
    try:
        stream.sendall(bytes([5, 1, 0]))
        assert read_exact(stream, 2) == bytes([5, 0])
        try:
            address = ipaddress.ip_address(destination)
            encoded = bytes([1 if address.version == 4 else 4]) + address.packed
        except ValueError:
            encoded = bytes([3, len(destination)]) + destination.encode("ascii")
        stream.sendall(bytes([5, 1, 0]) + encoded + struct.pack("!H", 443))
        response = read_exact(stream, 4)
        assert response[0:2] == bytes([5, 0]), "SOCKS connection was rejected"
        size = {1: 4, 4: 16}.get(response[3])
        if response[3] == 3:
            size = read_exact(stream, 1)[0]
        assert size is not None
        read_exact(stream, size + 2)
        stream.sendall(b"capture-target-test")
        return stream
    except Exception:
        stream.close()
        raise


def run_case(binary, context, case, directory):
    config = case["config"]
    # Only the fixture's loopback ports change. In particular targetStrategy is
    # left exactly as generated by brocade-core for this test case.
    with socket.socket() as listener, socket.socket() as reserve:
        listener.bind(("127.0.0.1", 0))
        listener.listen(1)
        reserve.bind(("127.0.0.1", 0))
        socks_port = reserve.getsockname()[1]
        reserve.close()
        config["inbounds"][0]["port"] = socks_port
        config["outbounds"][0]["settings"]["port"] = listener.getsockname()[1]
        config["log"] = {"loglevel": "none"}
        config_path = directory / (case["name"] + ".json")
        config_path.write_text(json.dumps(config))
        received = queue.Queue(maxsize=1)
        release = threading.Event()
        receiver = threading.Thread(
            target=capture_destination,
            args=(listener, context, config["outbounds"][0]["settings"]["password"], received, release),
            daemon=True,
        )
        receiver.start()
        process = subprocess.Popen(
            [str(binary), "run", "-config", str(config_path)],
            stdout=subprocess.DEVNULL,
            stderr=subprocess.DEVNULL,
        )
        stream = None
        try:
            for _ in range(100):
                assert process.poll() is None, "embedded Xray exited before SOCKS was ready"
                try:
                    with socket.create_connection(("127.0.0.1", socks_port), timeout=0.05):
                        break
                except OSError:
                    time.sleep(0.02)
            else:
                raise AssertionError("embedded Xray did not open its SOCKS listener")
            stream = socks_connect(socks_port, case["input"])
            destination = received.get(timeout=7)
            if isinstance(destination, Exception):
                raise destination
            assert destination["port"] == 443
            assert destination["address_type"] in case["expected_types"], destination
            assert destination["address"] in case["expected_addresses"], destination
            destination.update(
                case=case["name"],
                input=case["input"],
                target_strategy=config["outbounds"][0].get("targetStrategy", "AsIs (omitted)"),
            )
            return destination
        finally:
            if stream is not None:
                stream.close()
            release.set()
            process.terminate()
            try:
                process.wait(timeout=3)
            except subprocess.TimeoutExpired:
                process.kill()
                process.wait(timeout=3)
            receiver.join(timeout=6)
            assert not receiver.is_alive(), "AnyTLS capture peer did not stop"


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--binary", type=Path, required=True)
    parser.add_argument("--cases", type=Path, required=True)
    parser.add_argument("--certificate", type=Path, required=True)
    parser.add_argument("--key", type=Path, required=True)
    options = parser.parse_args()
    context = ssl.SSLContext(ssl.PROTOCOL_TLS_SERVER)
    context.load_cert_chain(options.certificate, options.key)
    cases = json.loads(options.cases.read_text())
    assert cases
    results = [run_case(options.binary, context, case, options.cases.parent) for case in cases]
    with options.binary.open("rb") as stream:
        digest = hashlib.file_digest(stream, "sha256").hexdigest()
    print(json.dumps({"xray_sha256": digest, "cases": results}, indent=2))


if __name__ == "__main__":
    main()
