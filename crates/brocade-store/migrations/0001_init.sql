    stored.snapshot,
    '{node_egress_dns}',
    (
        SELECT jsonb_agg(
            ranked.policy || jsonb_build_object('position', ranked.position)
            ORDER BY ranked.ordinality
        )
        FROM (
            SELECT item.policy,
                   item.ordinality,
