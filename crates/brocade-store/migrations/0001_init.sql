CREATE TABLE ingresses (
    vless_encryption_port INTEGER,
    vless_encryption_private_key TEXT,
    vless_encryption_public_key TEXT,
    vless_encryption_options JSONB NOT NULL DEFAULT '{}'::jsonb,
    id TEXT NOT NULL,
    app_id TEXT NOT NULL,
    chain_id TEXT NOT NULL,
    node_id TEXT NOT NULL,
    bind INET NOT NULL,
    port INTEGER NOT NULL,
    front_id TEXT,
    -- The whole shape of the wire: protocol, security layer and network layer named as one
    -- verified combination rather than as independent axes. 'vless-reality' is one TCP connection
    -- per client connection; 'vless-reality-xhttp' carries many streams inside one HTTP/2
    -- connection, which collapses the per-connection REALITY handshake — and with it the dial to
    -- the borrowed site that each handshake costs.
    --
    -- Named together because the axes are not independent: Vision flow control over XHTTP builds
    -- clean, passes `xray -test`, and refuses every connection at runtime.
    -- The TCP half, or NULL where this ingress serves QUIC only. Nullable because an ingress may
    -- carry either wire or both, and "both" is the point: one credential, one grant, two
    -- listeners, and a client that takes whichever gets through.
    transport_kind TEXT,
    -- The UDP half. Separate from transport_kind rather than another value inside it: they are
    -- not alternatives, they coexist, and one column cannot hold two answers.
    hy2_enabled BOOLEAN DEFAULT FALSE NOT NULL,
    -- AnyTLS is another independent TCP listener. It may coexist with VLESS and Hysteria 2. Its
    -- protocol security identity and target are independent; only the business-level user grants
    -- belong to the common ingress.
    anytls_enabled BOOLEAN DEFAULT FALSE NOT NULL,
    anytls_security TEXT DEFAULT 'tls' NOT NULL,
    -- AnyTLS REALITY does not inherit the VLESS target on the same ingress. NULL means the global
    -- site; an object stores the protocol's own global/custom provenance and custom override.
    anytls_reality JSONB,
    -- Generated independently from the VLESS identity. Nullable only while AnyTLS has never been
    -- enabled; the write path fills all three columns together before REALITY can be published.
    anytls_reality_private_key TEXT,
    anytls_reality_public_key TEXT,
    anytls_reality_short_ids JSONB,
    anytls_port INTEGER,
    anytls_padding_scheme JSONB DEFAULT '[]'::jsonb NOT NULL,
    anytls_masquerade_kind TEXT DEFAULT '404' NOT NULL,
    anytls_masquerade_content TEXT DEFAULT '' NOT NULL,
    anytls_masquerade_headers JSONB DEFAULT '{}'::jsonb NOT NULL,
    anytls_masquerade_status_code INTEGER DEFAULT 200 NOT NULL,
    reality_private_key TEXT NOT NULL,
    reality_public_key TEXT NOT NULL,
    reality_short_ids JSONB NOT NULL,
    reality_dest TEXT,
    reality_server_names JSONB NOT NULL,
    reality_flow TEXT,
    reality_fallback_mode TEXT DEFAULT 'global-site' NOT NULL,
    reality_fallback_limits JSONB DEFAULT '{"mode":"strict"}'::jsonb NOT NULL,
    -- Whether an unauthenticated fallback may reach names other than the borrowed one. Default on:
    -- a borrowed site is usually somebody's CDN, whose address answers for its neighbours too, and
    -- REALITY hands the connection over before it has read which name was asked for.
    reality_fallback_guard BOOLEAN DEFAULT TRUE NOT NULL,
    -- The path is stored rather than derived from the ingress id: it is copied into every client
    -- configuration, so deriving it would make renaming an ingress silently disconnect everyone.
    xhttp_path TEXT,
    -- Request/response Padding. NULL means the key is omitted and Xray owns its versioned
    -- default; POST upload controls are intentionally not managed.
    xhttp_tuning JSONB,
    -- A REALITY + XHTTP independent download may terminate TLS on a separate local port. The
    -- public host/port and download HTTP Host remain client-only and live in
    -- ingress_client_settings; these two columns are the only part the node compiler needs.
    xhttp_download_v4_origin_port INTEGER,
    xhttp_download_v6_origin_port INTEGER,
    -- How the client sends its upload half. NULL is "nobody chose", and then both ends resolve it
    -- the same way on their own. A stored value is written into the server config too, where it
    -- stops being a choice and becomes a filter: a server told to expect one shape refuses every
    -- client that names another.
    xhttp_mode TEXT,
    -- The UDP wire's own port. NULL exactly when this ingress has no UDP wire: the port belongs
    -- to the wire, and a row without that wire has no port to hold. It remains separate from the
    -- TCP `port` because a hopping range claims UDP numbers independently — see hy2_hop_* below.
    hy2_port INTEGER,
    -- The port-hopping range, inclusive, or NULL for "clients stay on hy2_port". Both ends are
    -- present or both absent; the range must contain hy2_port, because that is the only port the
    -- server actually binds — the rest reach it through the machine's redirect.
    hy2_hop_start INTEGER,
    hy2_hop_end INTEGER,
    hy2_up TEXT,
    hy2_down TEXT,
    hy2_congestion TEXT DEFAULT 'brutal' NOT NULL,
    -- BBR 策略。只在这条连接实际跑 BBR 时被读到（congestion 是 bbr，或者是 brutal
    -- 而带宽没填）。xray 把缺省当作 standard，所以这里也以 standard 为默认。
    hy2_bbr_profile TEXT DEFAULT 'standard' NOT NULL,
    -- finalmask.quicParams 里的调优项。全部可空，空 = 不写这个键，由 xray 用它自己那一版的
    -- 默认值。存我们以为的默认值会把今天的上游默认固化进产物，产物就不再跟着部署的版本走。
    -- 下面每条 CHECK 的边界都取自 xray 的构建期校验，越界会让它起不来。
    hy2_quic_init_stream_window BIGINT,
    hy2_quic_max_stream_window BIGINT,
    hy2_quic_init_conn_window BIGINT,
    hy2_quic_max_conn_window BIGINT,
    hy2_quic_max_idle_secs INTEGER,
    hy2_quic_keepalive_secs INTEGER,
    hy2_quic_max_incoming_streams INTEGER,
    hy2_quic_disable_pmtud BOOLEAN DEFAULT FALSE NOT NULL,
    hy2_obfs_password TEXT,
    hy2_masquerade_kind TEXT DEFAULT 'not-found' NOT NULL,
    hy2_masquerade_url TEXT,
    -- What this entrance refuses to carry, before anything its chain says. Five columns rather
    -- than one JSONB blob: each is a separate operator decision with its own default, and a blob
    -- would make "which of these is on" a question you have to parse to answer — including in the
    -- WHERE that decides whether a write changed anything.
    --
    -- Four default TRUE. They refuse what nobody knowingly wants: reaching the fleet's own overlay
    -- from outside, seeding torrents from a shared address, sending mail from an address that gets
    -- blacklisted for it, and bouncing amplification traffic off open UDP services. The fifth is
    -- FALSE because it takes games and voice with it.
    guard_no_private BOOLEAN DEFAULT TRUE NOT NULL,
    guard_no_bittorrent BOOLEAN DEFAULT TRUE NOT NULL,
    guard_no_mail BOOLEAN DEFAULT TRUE NOT NULL,
    guard_no_udp_amplification BOOLEAN DEFAULT TRUE NOT NULL,
    guard_tcp_and_quic_only BOOLEAN DEFAULT FALSE NOT NULL,
    -- The outward projection: the address written in subscriptions. One pair per family, with NULL
    -- meaning that family is not projected. See brocade_core::model::Projection.
    projection_v4_host TEXT,
    projection_v4_port INTEGER,
    projection_v6_host TEXT,
    projection_v6_port INTEGER,
    -- Per-protocol mappings. The legacy VLESS columns remain authoritative for that protocol so
    -- an older Console can still roll back safely; NULL means a historical shared mapping.
    protocol_projection JSONB,
    created_at TIMESTAMPTZ DEFAULT now() NOT NULL,
    created_revision BIGINT,
    CONSTRAINT ingresses_port_check CHECK (((port >= 1) AND (port <= 65535))),
    CONSTRAINT ingresses_vless_encryption_port_check CHECK (
        vless_encryption_port IS NULL OR (vless_encryption_port BETWEEN 1 AND 65535
            AND vless_encryption_private_key IS NOT NULL AND vless_encryption_public_key IS NOT NULL)
    ),
    -- xhttp without a path is an ingress no client can reach: the path is what the server matches
    -- a request against, and a mismatch is refused outright (`failed to validate path`).
    CONSTRAINT ingresses_xhttp_path CHECK (((transport_kind IS NULL OR transport_kind NOT IN ('vless-reality-xhttp', 'vless-tls-xhttp')) OR (xhttp_path ~ '^/'))),
    CONSTRAINT ingresses_xhttp_tuning_shape CHECK (
        xhttp_tuning IS NULL OR ((
            jsonb_typeof(xhttp_tuning) = 'object'
            AND xhttp_tuning - 'x_padding_bytes' = '{}'::jsonb
            AND (NOT (xhttp_tuning ? 'x_padding_bytes') OR (
                jsonb_typeof(xhttp_tuning -> 'x_padding_bytes') = 'object'
                AND (xhttp_tuning -> 'x_padding_bytes' ->> 'from')::BIGINT BETWEEN 1 AND 4096
                AND (xhttp_tuning -> 'x_padding_bytes' ->> 'to')::BIGINT BETWEEN 1 AND 4096
                AND (xhttp_tuning -> 'x_padding_bytes' ->> 'from')::BIGINT
                    <= (xhttp_tuning -> 'x_padding_bytes' ->> 'to')::BIGINT
            ))
        ) IS TRUE)
    ),
    CONSTRAINT ingresses_xhttp_mode_known CHECK (((xhttp_mode IS NULL) OR (xhttp_mode IN ('packet-up', 'stream-up', 'stream-one')))),
    CONSTRAINT ingresses_xhttp_download_v4_origin_check CHECK (
        xhttp_download_v4_origin_port IS NULL
        OR (transport_kind = 'vless-reality-xhttp'
            AND xhttp_download_v4_origin_port BETWEEN 1 AND 65535)
    ),
    CONSTRAINT ingresses_xhttp_download_v6_origin_check CHECK (
        xhttp_download_v6_origin_port IS NULL
        OR (transport_kind = 'vless-reality-xhttp'
            AND xhttp_download_v6_origin_port BETWEEN 1 AND 65535)
    ),
    CONSTRAINT ingresses_hy2_port_present CHECK ((hy2_port IS NOT NULL) = hy2_enabled),
    CONSTRAINT ingresses_hy2_port_range CHECK ((hy2_port IS NULL) OR (hy2_port BETWEEN 1 AND 65535)),
    -- Same number on both wires is legal at the socket layer and refused anyway: a hop range is
    -- one redirect rule over a run of ports, and one written without `-p udp` takes the TCP wire
    -- with it. The compiler says the same thing (`ingress.hy2-port-shared`); this is that
    -- invariant at the layer that outlives the process.
    CONSTRAINT ingresses_hy2_port_distinct CHECK ((hy2_port IS NULL) OR (transport_kind IS NULL) OR (hy2_port <> port)),
    CONSTRAINT ingresses_hy2_hop_pair CHECK ((hy2_hop_start IS NULL) = (hy2_hop_end IS NULL)),
    CONSTRAINT ingresses_hy2_hop_range CHECK (
        hy2_hop_start IS NULL
        OR (hy2_hop_start BETWEEN 1 AND 65535 AND hy2_hop_end BETWEEN 1 AND 65535
            AND hy2_hop_start <= hy2_hop_end
            AND hy2_port BETWEEN hy2_hop_start AND hy2_hop_end)
    ),
    CONSTRAINT ingresses_hy2_bandwidth_pair CHECK ((hy2_up IS NULL) = (hy2_down IS NULL)),
    CONSTRAINT ingresses_hy2_congestion_check CHECK (hy2_congestion IN ('brutal', 'bbr', 'reno', 'force-brutal')),
    CONSTRAINT ingresses_hy2_bbr_profile_check CHECK (hy2_bbr_profile IN ('standard', 'conservative', 'aggressive')),
    -- 四个窗口同一条下限。xray：`... must be at least 16384`。
    CONSTRAINT ingresses_hy2_quic_windows_check CHECK (
        (hy2_quic_init_stream_window IS NULL OR hy2_quic_init_stream_window >= 16384)
        AND (hy2_quic_max_stream_window IS NULL OR hy2_quic_max_stream_window >= 16384)
        AND (hy2_quic_init_conn_window IS NULL OR hy2_quic_init_conn_window >= 16384)
        AND (hy2_quic_max_conn_window IS NULL OR hy2_quic_max_conn_window >= 16384)
    ),
    CONSTRAINT ingresses_hy2_quic_max_idle_check CHECK (
        hy2_quic_max_idle_secs IS NULL OR hy2_quic_max_idle_secs BETWEEN 4 AND 120
    ),
    CONSTRAINT ingresses_hy2_quic_keepalive_check CHECK (
        hy2_quic_keepalive_secs IS NULL OR hy2_quic_keepalive_secs BETWEEN 2 AND 60
    ),
    CONSTRAINT ingresses_hy2_quic_streams_check CHECK (
        hy2_quic_max_incoming_streams IS NULL OR hy2_quic_max_incoming_streams >= 8
    ),
    CONSTRAINT ingresses_hy2_obfs_password_check CHECK ((hy2_obfs_password IS NULL) OR (btrim(hy2_obfs_password) <> '')),
    CONSTRAINT ingresses_hy2_masquerade_kind_check CHECK (hy2_masquerade_kind IN ('not-found', 'proxy')),
    CONSTRAINT ingresses_hy2_masquerade_check CHECK (
        (hy2_masquerade_kind = 'not-found' AND hy2_masquerade_url IS NULL)
        OR (hy2_masquerade_kind = 'proxy' AND hy2_masquerade_url LIKE 'https://%')
    ),
    -- "No projection" can only be expressed by both columns being NULL. An empty string and a
    -- half-filled pair cannot be written here at all — once an empty host sits in the database,
    -- nobody can say whether it was meant to be off or was filled in halfway, while the artifacts
    -- end up with an undialable address and the machine side looks entirely fine.
    --
    -- Spelling out IS NULL / IS NOT NULL on both branches is required: a CHECK refuses only where
    -- the result is FALSE, and omitting them has "host present, port NULL" evaluate to NULL and
    -- pass.
    CONSTRAINT ingresses_projection_v4_check CHECK (
        (projection_v4_host IS NULL AND projection_v4_port IS NULL)
        OR (projection_v4_host IS NOT NULL AND projection_v4_port IS NOT NULL
            AND btrim(projection_v4_host) <> ''
            AND projection_v4_port >= 1 AND projection_v4_port <= 65535)
    ),
    CONSTRAINT ingresses_projection_v6_check CHECK (
        (projection_v6_host IS NULL AND projection_v6_port IS NULL)
        OR (projection_v6_host IS NOT NULL AND projection_v6_port IS NOT NULL
            AND btrim(projection_v6_host) <> ''
            AND projection_v6_port >= 1 AND projection_v6_port <= 65535)
    ),
    CONSTRAINT ingresses_protocol_projection_shape CHECK (
        protocol_projection IS NULL OR jsonb_typeof(protocol_projection) = 'object'
    ),
    CONSTRAINT ingresses_reality_fallback_mode_check CHECK (
        reality_fallback_mode IN ('global-site', 'node-certificate', 'custom-site')
    ),
    CONSTRAINT ingresses_reality_fallback_limits_check CHECK (
        jsonb_typeof(reality_fallback_limits) = 'object'
        AND reality_fallback_limits ->> 'mode' IN ('off', 'balanced', 'strict', 'custom')
    ),
    CONSTRAINT ingresses_reality_server_names_check CHECK ((jsonb_typeof(reality_server_names) = 'array')),
    CONSTRAINT ingresses_reality_short_ids_check CHECK (brocade_valid_reality_short_ids(reality_short_ids)),
    CONSTRAINT ingresses_transport_kind_check CHECK ((transport_kind IS NULL OR transport_kind IN ('vless-reality', 'vless-reality-xhttp', 'vless-tls', 'vless-tls-xhttp'))),
    CONSTRAINT ingresses_anytls_port_present CHECK ((anytls_port IS NOT NULL) = anytls_enabled),
    CONSTRAINT ingresses_anytls_security_check CHECK (anytls_security IN ('tls', 'reality')),
    CONSTRAINT ingresses_anytls_reality_check CHECK (
        ((NOT anytls_enabled OR anytls_security = 'tls') AND anytls_reality IS NULL)
        OR (anytls_enabled AND anytls_security = 'reality'
            AND anytls_reality IS NOT NULL
            AND jsonb_typeof(anytls_reality) = 'object'
            AND anytls_reality ->> 'fallback_mode' IN ('global-site', 'custom-site')
        )
    ),
    CONSTRAINT ingresses_anytls_reality_identity_check CHECK (
        (anytls_reality_private_key IS NULL
            AND anytls_reality_public_key IS NULL
            AND anytls_reality_short_ids IS NULL)
        OR (anytls_reality_private_key IS NOT NULL
            AND anytls_reality_public_key IS NOT NULL
            AND anytls_reality_short_ids IS NOT NULL
            AND brocade_valid_reality_short_ids(anytls_reality_short_ids))
    ),
    CONSTRAINT ingresses_anytls_port_range CHECK (anytls_port IS NULL OR anytls_port BETWEEN 1 AND 65535),
    CONSTRAINT ingresses_anytls_port_distinct CHECK (
        anytls_port IS NULL OR transport_kind IS NULL OR anytls_port <> port
    ),
    CONSTRAINT ingresses_anytls_padding_scheme_check CHECK (jsonb_typeof(anytls_padding_scheme) = 'array'),
    CONSTRAINT ingresses_anytls_masquerade_kind_check CHECK (anytls_masquerade_kind IN ('404', 'string')),
    CONSTRAINT ingresses_anytls_masquerade_headers_check CHECK (jsonb_typeof(anytls_masquerade_headers) = 'object'),
    CONSTRAINT ingresses_anytls_masquerade_status_check CHECK (
        anytls_masquerade_kind <> 'string'
        OR anytls_masquerade_status_code BETWEEN 200 AND 599
    ),
    -- An ingress with neither wire listens on nothing and would compile to an inbound-less
    -- machine. The model makes it unrepresentable (`IngressWires` is an enum, not two Options);
    -- this is the same invariant at the layer that outlives the process.
    CONSTRAINT ingresses_has_a_wire CHECK ((transport_kind IS NOT NULL OR anytls_enabled OR hy2_enabled OR vless_encryption_port IS NOT NULL)),
    CONSTRAINT ingresses_app_id_id_key UNIQUE (app_id, id),

    CONSTRAINT ingresses_pkey PRIMARY KEY (id),
    CONSTRAINT ingresses_app_id_fkey FOREIGN KEY (app_id) REFERENCES apps(id) ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT ingresses_chain_id_fkey FOREIGN KEY (chain_id) REFERENCES chains(id) ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT ingresses_created_revision_fkey FOREIGN KEY (created_revision) REFERENCES revisions(id),
    CONSTRAINT ingresses_front_id_fkey FOREIGN KEY (front_id) REFERENCES fronts(id) ON DELETE SET NULL,
    CONSTRAINT ingresses_node_id_fkey FOREIGN KEY (node_id) REFERENCES nodes(id) ON DELETE RESTRICT
);

-- Client dialer controls have an independent serving checkpoint. Their mutable authoring values
-- stay outside the topology row so changing Host, XMUX or the REALITY ClientHello does not look
-- like a node configuration edit.
CREATE TABLE ingress_client_settings (
    ingress_id TEXT NOT NULL,
    -- NULL follows the global REALITY client default.
    reality_fingerprint TEXT,
    xhttp_host TEXT,
    xhttp_xmux JSONB,
    -- Client-only independent download endpoints. Their REALITY origin ports are kept on the
    -- ingress topology row above; these JSON objects intentionally contain only dialer fields.
    xhttp_download_v4 JSONB,
    xhttp_download_v6 JSONB,
    -- AnyTLS client session pooling. NULL leaves the choice to each consuming client.
    anytls_idle_session_check_interval BIGINT,
    anytls_idle_session_timeout BIGINT,
    anytls_min_idle_session BIGINT,
    updated_at TIMESTAMPTZ DEFAULT now() NOT NULL,
    CONSTRAINT ingress_client_settings_pkey PRIMARY KEY (ingress_id),
    CONSTRAINT ingress_client_settings_ingress_fkey
        FOREIGN KEY (ingress_id) REFERENCES ingresses(id)
        ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT ingress_client_settings_reality_fingerprint_check
        CHECK (reality_fingerprint IS NULL OR btrim(reality_fingerprint) <> ''),
    CONSTRAINT ingress_client_settings_xhttp_host_check
        CHECK (xhttp_host IS NULL OR btrim(xhttp_host) <> ''),
    CONSTRAINT ingress_client_settings_xhttp_download_v4_check
        CHECK (xhttp_download_v4 IS NULL OR brocade_valid_xhttp_download(xhttp_download_v4)),
    CONSTRAINT ingress_client_settings_xhttp_download_v6_check
        CHECK (xhttp_download_v6 IS NULL OR brocade_valid_xhttp_download(xhttp_download_v6)),
    CONSTRAINT ingress_client_anytls_check_interval_range CHECK (
        anytls_idle_session_check_interval IS NULL
        OR anytls_idle_session_check_interval BETWEEN 1 AND 4294967295
    ),
    CONSTRAINT ingress_client_anytls_timeout_range CHECK (
        anytls_idle_session_timeout IS NULL
        OR anytls_idle_session_timeout BETWEEN 1 AND 4294967295
    ),
    CONSTRAINT ingress_client_anytls_min_idle_range CHECK (
        anytls_min_idle_session IS NULL
        OR anytls_min_idle_session BETWEEN 0 AND 4294967295
    ),
    CONSTRAINT ingress_client_settings_xhttp_xmux_shape CHECK (
        xhttp_xmux IS NULL OR ((
            jsonb_typeof(xhttp_xmux) = 'object'
            AND ((
                jsonb_typeof(xhttp_xmux -> 'max_concurrency') = 'number'
                AND (xhttp_xmux ->> 'max_concurrency')::INTEGER BETWEEN 1 AND 128
                AND NOT (xhttp_xmux ? 'max_connections')
            ) OR (
                jsonb_typeof(xhttp_xmux -> 'max_connections') = 'number'
                AND (xhttp_xmux ->> 'max_connections')::INTEGER BETWEEN 1 AND 128
                AND NOT (xhttp_xmux ? 'max_concurrency')
            ))
            AND jsonb_typeof(xhttp_xmux -> 'h_max_request_times') = 'object'
            AND jsonb_typeof(xhttp_xmux -> 'h_max_request_times' -> 'from') = 'number'
            AND jsonb_typeof(xhttp_xmux -> 'h_max_request_times' -> 'to') = 'number'
            AND (xhttp_xmux -> 'h_max_request_times' ->> 'from')::BIGINT BETWEEN 1 AND 2147483647
            AND (xhttp_xmux -> 'h_max_request_times' ->> 'to')::BIGINT BETWEEN 1 AND 2147483647
            AND (xhttp_xmux -> 'h_max_request_times' ->> 'from')::BIGINT
                <= (xhttp_xmux -> 'h_max_request_times' ->> 'to')::BIGINT
            AND jsonb_typeof(xhttp_xmux -> 'h_max_reusable_secs') = 'object'
            AND jsonb_typeof(xhttp_xmux -> 'h_max_reusable_secs' -> 'from') = 'number'
            AND jsonb_typeof(xhttp_xmux -> 'h_max_reusable_secs' -> 'to') = 'number'
            AND (xhttp_xmux -> 'h_max_reusable_secs' ->> 'from')::BIGINT BETWEEN 1 AND 2147483647
            AND (xhttp_xmux -> 'h_max_reusable_secs' ->> 'to')::BIGINT BETWEEN 1 AND 2147483647
            AND (xhttp_xmux -> 'h_max_reusable_secs' ->> 'from')::BIGINT
                <= (xhttp_xmux -> 'h_max_reusable_secs' ->> 'to')::BIGINT
            AND (
                NOT (xhttp_xmux ? 'h_keep_alive_period_secs')
                OR (
                    jsonb_typeof(xhttp_xmux -> 'h_keep_alive_period_secs') = 'number'
                    AND ((xhttp_xmux ->> 'h_keep_alive_period_secs')::INTEGER = -1
                        OR (xhttp_xmux ->> 'h_keep_alive_period_secs')::INTEGER BETWEEN 1 AND 3600)
                )
            )
        ) IS TRUE)
    )
);

