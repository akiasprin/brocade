    CONSTRAINT ingresses_projection_v6_download_mux_check CHECK (
        projection_v6_download_mux IS NULL
        OR (projection_v6_download_host IS NOT NULL AND projection_v6_download_mux BETWEEN 2 AND 128)
    ),
    CONSTRAINT ingresses_reality_fallback_mode_check CHECK (
        reality_fallback_mode IN ('global-site', 'node-certificate', 'custom-site')
    ),
    CONSTRAINT ingresses_reality_fallback_limits_check CHECK (
        jsonb_typeof(reality_fallback_limits) = 'object'
        AND reality_fallback_limits ->> 'mode' IN ('off', 'balanced', 'strict', 'custom')
    ),
    CONSTRAINT ingresses_reality_server_names_check CHECK ((jsonb_typeof(reality_server_names) = 'array')),
    CONSTRAINT ingresses_reality_short_ids_check CHECK (brocade_valid_reality_short_ids(reality_short_ids)),
