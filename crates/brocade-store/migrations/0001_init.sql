-- The processes we put on the machine. Latest only — one row per (node, process).
--
-- No time series, unlike the two tables above. The console asks one question of this data ("is the
-- machine busy, or are we busy"), which the latest reading answers; RSS history would quadruple
-- the row count to answer a question nobody asks. The one temporal fact that matters — "xray
-- restarted" — is still readable, by comparing started_at against the machine's uptime.
--
-- rss_bytes is NULL for wg (a kernel module has none) and for a process that is not running at
-- all; those two are told apart by started_at, which is likewise NULL for wg but present for any
-- process that ever ran. xray absent is an identity, not a fault: a pure wg backbone relay has no
-- xray, and reporting that as a problem sends operators to fix a healthy machine.
CREATE TABLE IF NOT EXISTS node_process_state (
    node_id TEXT NOT NULL,
    proc TEXT NOT NULL,
    rss_bytes BIGINT,
    cpu_pct REAL,
    started_at TIMESTAMPTZ,
    fds BIGINT,
    fd_limit BIGINT,
    observed_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT node_process_state_proc CHECK ((proc IN ('xray', 'wg', 'phantun', 'agent'))),
    CONSTRAINT node_process_state_values CHECK ((((rss_bytes IS NULL) OR (rss_bytes >= 0)) AND ((cpu_pct IS NULL) OR (cpu_pct >= 0)) AND ((fds IS NULL) OR (fds >= 0)) AND ((fd_limit IS NULL) OR (fd_limit > 0)))),
    CONSTRAINT node_process_state_pkey PRIMARY KEY (node_id, proc),
