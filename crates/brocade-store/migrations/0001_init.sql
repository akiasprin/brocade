-- Reusable tenant-level proxy targets. Credentials are sealed independently from the JSON
-- protocol options: this keeps a query or dump of the ordinary configuration columns from
-- exposing them, while still allowing protocol-specific settings to evolve without a column per
-- knob. Projects consume these resources through rule/front references but do not own them. A
-- globally unique id keeps those references unambiguous across tenant ancestry, while the same
-- resource is only compiled onto nodes that actually reference it.
CREATE TABLE external_outbounds (
    id TEXT NOT NULL,
    tenant_id TEXT NOT NULL,
    name TEXT NOT NULL,
    address TEXT NOT NULL,
    port INTEGER NOT NULL,
    protocol TEXT NOT NULL,
    credential_sealed TEXT NOT NULL,
    protocol_options JSONB DEFAULT '{}'::jsonb NOT NULL,
    security JSONB NOT NULL,
    created_at TIMESTAMPTZ DEFAULT now() NOT NULL,
    created_revision BIGINT,
    CONSTRAINT external_outbounds_pkey PRIMARY KEY (id),
    CONSTRAINT external_outbounds_port_check CHECK ((port >= 1) AND (port <= 65535)),
    CONSTRAINT external_outbounds_protocol_check CHECK ((protocol IN ('anytls', 'vless', 'shadowsocks2022', 'socks5', 'http_connect', 'wireguard', 'warp', 'vpngate'))),
    CONSTRAINT external_outbounds_warp_id_check CHECK ((protocol <> 'warp') OR (id ~ '^warp-[0-9a-f]{4}-[0-9a-f]{4}$')),
    CONSTRAINT external_outbounds_vpngate_id_check CHECK ((protocol <> 'vpngate') OR (id ~ '^vpngate-[0-9a-f]{4}-[0-9a-f]{4}$')),
    CONSTRAINT external_outbounds_custom_id_check CHECK ((protocol IN ('warp', 'vpngate')) OR (id ~ '^custom-[0-9a-f]{4}-[0-9a-f]{4}$')),
    CONSTRAINT external_outbounds_tenant_id_fkey FOREIGN KEY (tenant_id) REFERENCES tenants(id) ON DELETE RESTRICT,
    CONSTRAINT external_outbounds_created_revision_fkey FOREIGN KEY (created_revision) REFERENCES revisions(id)
);

-- Console-originated health checks are operational state. They deliberately do not enter the
-- immutable model: changing a cadence must not create a data-plane revision or restart a node.
CREATE TABLE external_outbound_probe_policies (
    outbound_id TEXT NOT NULL,
    enabled BOOLEAN DEFAULT false NOT NULL,
    interval_secs INTEGER DEFAULT 300 NOT NULL,
    timeout_secs INTEGER DEFAULT 10 NOT NULL,
    next_run_at TIMESTAMPTZ,
    updated_by TEXT NOT NULL,
    updated_at TIMESTAMPTZ DEFAULT now() NOT NULL,
    CONSTRAINT external_outbound_probe_policies_pkey PRIMARY KEY (outbound_id),
    CONSTRAINT external_outbound_probe_policies_outbound_fkey
        FOREIGN KEY (outbound_id) REFERENCES external_outbounds(id) ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT external_outbound_probe_policies_interval_known
        CHECK (interval_secs IN (60, 300, 900, 1800, 3600)),
    CONSTRAINT external_outbound_probe_policies_timeout_range
        CHECK (timeout_secs BETWEEN 1 AND 120),
    CONSTRAINT external_outbound_probe_policies_next_matches_enabled
        CHECK ((enabled AND next_run_at IS NOT NULL) OR (NOT enabled AND next_run_at IS NULL))
);

-- One durable row per manual or scheduled attempt. Serving runs reconstruct their secret-bearing
-- plan from an immutable topology revision. A manual draft run instead keeps only its selected
-- outbound as one AEAD-sealed document: browser drafts have no durable revision and must be frozen
-- at the click boundary, but their credentials must never become readable database columns. The
-- sealed document is erased at the terminal transition. Runs intentionally keep no FK to
-- external_outbounds so deleting a draft resource cannot erase operational evidence.
CREATE TABLE external_outbound_probe_runs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    tenant_id TEXT NOT NULL,
    outbound_id TEXT NOT NULL,
    outbound_name TEXT NOT NULL,
    protocol TEXT NOT NULL,
    trigger TEXT NOT NULL,
    source TEXT NOT NULL,
    scheduled_for TIMESTAMPTZ,
    topology_revision_id BIGINT NOT NULL,
    serving_generation BIGINT,
    draft_sha256 TEXT,
    outbound_sealed TEXT,
    settings_revision_id BIGINT NOT NULL,
    endpoint_url TEXT NOT NULL,
    timeout_secs INTEGER NOT NULL,
    config_sha256 TEXT,
    status TEXT DEFAULT 'queued' NOT NULL,
    phase TEXT DEFAULT 'queued' NOT NULL,
    result TEXT,
    ttfb_ms INTEGER,
    http_status INTEGER,
    exit_ip TEXT,
    exit_loc TEXT,
    attempt_count INTEGER DEFAULT 0 NOT NULL,
    error_code TEXT,
    error_detail TEXT,
    requested_by TEXT,
    queued_at TIMESTAMPTZ DEFAULT now() NOT NULL,
    started_at TIMESTAMPTZ,
    finished_at TIMESTAMPTZ,
    lease_owner TEXT,
    lease_generation BIGINT DEFAULT 0 NOT NULL,
    lease_until TIMESTAMPTZ,
    cancel_requested_at TIMESTAMPTZ,
    CONSTRAINT external_outbound_probe_runs_pkey PRIMARY KEY (id),
    CONSTRAINT external_outbound_probe_runs_tenant_fkey
        FOREIGN KEY (tenant_id) REFERENCES tenants(id) ON DELETE CASCADE,
    CONSTRAINT external_outbound_probe_runs_topology_revision_fkey
        FOREIGN KEY (topology_revision_id) REFERENCES revisions(id) ON DELETE RESTRICT,
    CONSTRAINT external_outbound_probe_runs_settings_revision_fkey
        FOREIGN KEY (settings_revision_id) REFERENCES revisions(id) ON DELETE RESTRICT,
    CONSTRAINT external_outbound_probe_runs_protocol_known
        CHECK (protocol IN ('anytls', 'vless', 'shadowsocks2022', 'socks5', 'http_connect', 'wireguard', 'warp', 'vpngate')),
    CONSTRAINT external_outbound_probe_runs_trigger_known
        CHECK (trigger IN ('manual', 'scheduled')),
    CONSTRAINT external_outbound_probe_runs_source_known
        CHECK (source IN ('serving', 'draft')),
    CONSTRAINT external_outbound_probe_runs_schedule_matches_trigger
        CHECK ((trigger = 'manual' AND scheduled_for IS NULL) OR (trigger = 'scheduled' AND scheduled_for IS NOT NULL)),
    CONSTRAINT external_outbound_probe_runs_source_coherent CHECK (
        (source = 'serving'
            AND serving_generation IS NOT NULL
            AND draft_sha256 IS NULL
            AND outbound_sealed IS NULL)
        OR (source = 'draft'
            AND trigger = 'manual'
            AND serving_generation IS NULL
            AND draft_sha256 IS NOT NULL
            AND draft_sha256 ~ '^[0-9a-f]{64}$'
            AND ((status IN ('queued', 'running')) = (outbound_sealed IS NOT NULL)))
    ),
    CONSTRAINT external_outbound_probe_runs_status_known
        CHECK (status IN ('queued', 'running', 'succeeded', 'failed', 'canceled', 'unsupported')),
    CONSTRAINT external_outbound_probe_runs_phase_known
        CHECK (phase IN ('queued', 'preparing', 'starting-xray', 'requesting', 'finished')),
    CONSTRAINT external_outbound_probe_runs_result_known
        CHECK (result IS NULL OR result IN ('ok', 'timeout', 'connect-failed', 'target-failed', 'unsupported', 'canceled', 'interrupted')),
    CONSTRAINT external_outbound_probe_runs_timeout_range CHECK (timeout_secs BETWEEN 1 AND 120),
    CONSTRAINT external_outbound_probe_runs_ttfb_range
        CHECK (ttfb_ms IS NULL OR ttfb_ms BETWEEN 0 AND 600000),
    CONSTRAINT external_outbound_probe_runs_http_status_range
        CHECK (http_status IS NULL OR http_status BETWEEN 100 AND 599),
    CONSTRAINT external_outbound_probe_runs_attempt_count_range
        CHECK (attempt_count BETWEEN 0 AND 2),
    CONSTRAINT external_outbound_probe_runs_config_sha256_shape
        CHECK (config_sha256 IS NULL OR config_sha256 ~ '^[0-9a-f]{64}$'),
    CONSTRAINT external_outbound_probe_runs_state_coherent CHECK (
        (status = 'queued' AND phase = 'queued' AND result IS NULL)
        OR (status = 'running' AND phase IN ('preparing', 'starting-xray', 'requesting') AND result IS NULL)
        OR (status = 'succeeded' AND phase = 'finished' AND result = 'ok')
        OR (status = 'failed' AND phase = 'finished'
            AND result IN ('timeout', 'connect-failed', 'target-failed', 'interrupted'))
        OR (status = 'canceled' AND phase = 'finished' AND result = 'canceled')
        OR (status = 'unsupported' AND phase = 'finished' AND result = 'unsupported')
    ),
    CONSTRAINT external_outbound_probe_runs_success_has_measurement
        CHECK ((status = 'succeeded' AND result = 'ok' AND ttfb_ms IS NOT NULL) OR status <> 'succeeded'),
    CONSTRAINT external_outbound_probe_runs_terminal_has_finished_at
        CHECK ((status IN ('succeeded', 'failed', 'canceled', 'unsupported')) = (finished_at IS NOT NULL))
);

-- Runs outlive mutable outbounds, so a deleted id may be assigned to another tenant while an old
-- run is still active. Tenant is therefore part of every deduplication and lookup identity.
CREATE UNIQUE INDEX external_outbound_probe_runs_scheduled_slot
    ON external_outbound_probe_runs (tenant_id, outbound_id, scheduled_for)
    WHERE scheduled_for IS NOT NULL;
CREATE UNIQUE INDEX external_outbound_probe_runs_one_active
    ON external_outbound_probe_runs (tenant_id, outbound_id, source)
    WHERE status IN ('queued', 'running');
CREATE INDEX external_outbound_probe_runs_outbound_recent
    ON external_outbound_probe_runs (tenant_id, outbound_id, finished_at DESC, id DESC)
    WHERE finished_at IS NOT NULL;
CREATE INDEX external_outbound_probe_runs_outbound_latest
    ON external_outbound_probe_runs (tenant_id, outbound_id, queued_at DESC, id DESC);
CREATE INDEX external_outbound_probe_runs_tenant_recent
    ON external_outbound_probe_runs (tenant_id, finished_at DESC);
CREATE INDEX external_outbound_probe_runs_finished
    ON external_outbound_probe_runs (finished_at)
    WHERE finished_at IS NOT NULL;

-- VPN Gate is a volatile public catalogue, but Brocade must not make its observability volatile.
-- Every fetch is recorded, profiles are content-addressed, and every accepted row gets an
-- immutable observation. `vpngate_servers` is only the fast current projection; old observations
-- and profile bytes are never deleted by the synchronizer.
CREATE TABLE vpngate_sync_runs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    source_url TEXT NOT NULL,
    worker_id TEXT NOT NULL,
    trigger TEXT NOT NULL,
    status TEXT DEFAULT 'running' NOT NULL,
    content_sha256 TEXT,
    fetched_rows INTEGER,
    accepted_rows INTEGER,
    rejected_rows INTEGER,
    error_code TEXT,
    error_detail TEXT,
    started_at TIMESTAMPTZ DEFAULT now() NOT NULL,
    finished_at TIMESTAMPTZ,
    CONSTRAINT vpngate_sync_runs_pkey PRIMARY KEY (id),
    CONSTRAINT vpngate_sync_runs_source_https CHECK (source_url ~ '^https://'),
    CONSTRAINT vpngate_sync_runs_worker_shape CHECK (length(btrim(worker_id)) BETWEEN 1 AND 128),
    CONSTRAINT vpngate_sync_runs_trigger_known CHECK (trigger IN ('scheduled', 'manual', 'startup')),
    CONSTRAINT vpngate_sync_runs_status_known CHECK (status IN ('running', 'succeeded', 'failed')),
    CONSTRAINT vpngate_sync_runs_sha_shape CHECK (content_sha256 IS NULL OR content_sha256 ~ '^[0-9a-f]{64}$'),
    CONSTRAINT vpngate_sync_runs_counts_nonnegative CHECK (
        (fetched_rows IS NULL OR fetched_rows >= 0)
        AND (accepted_rows IS NULL OR accepted_rows >= 0)
        AND (rejected_rows IS NULL OR rejected_rows >= 0)
    ),
    CONSTRAINT vpngate_sync_runs_terminal_coherent CHECK (
        (status = 'running' AND finished_at IS NULL)
        OR (status = 'succeeded' AND finished_at IS NOT NULL AND content_sha256 IS NOT NULL
            AND fetched_rows IS NOT NULL AND accepted_rows IS NOT NULL AND rejected_rows IS NOT NULL)
        OR (status = 'failed' AND finished_at IS NOT NULL AND error_code IS NOT NULL)
    )
);

