-- The domains this fleet issues node certificates under, and what is needed to issue them.
--
-- # Why a table rather than a column on control_state
--
-- One domain is all the console offers today, so a column would do. It is a table because the
-- expensive part of splitting a fleet across domains later is not the schema — it is that a node's
-- certificate name is the SNI its clients send. Moving a node to another domain renames it,
-- which re-issues its certificate and invalidates every client configuration pointing at it. A
-- fleet whose clients cannot be changed therefore cannot be split after the fact at all.
--
-- So the shape that allows it costs a table and a foreign key now, and buys the option later. The
-- console deliberately does not expose the option yet: one domain, one row.
--
-- # Why the fleet wants that option
--
-- Every node under one domain shares its fate. The domain being blocked, flagged, seized, or
-- simply enumerated out of Certificate Transparency takes the whole fleet at once. Two domains cut
-- that in half, and per-tenant domains stop one customer's ingresses from being visibly the same
-- operator as another's.
CREATE TABLE IF NOT EXISTS cert_domains (
    id TEXT NOT NULL,
    -- The registrable domain, no leading dot: `example.net`. Node names are built beneath it as
    -- `*.<label>.<domain>` plus the bare `<label>.<domain>` — a wildcard covers one label and does
    -- not cover itself, so both names are needed and both go in the same certificate.
    domain TEXT NOT NULL,
    -- Only cloudflare is implemented. Named rather than assumed so that a second provider is a new
    -- value here instead of a schema change, and so that an unimplemented one fails loudly.
    dns_provider TEXT DEFAULT 'cloudflare' NOT NULL,
    -- The DNS credential, sealed (see brocade-store/src/secrets.rs) — never the raw token.
    --
    -- It is the most dangerous secret this database holds: Cloudflare tokens cannot be scoped
    -- below a zone, so this one can rewrite every record in the domain. That is also the reason
    -- the fleet should sit on a domain of its own rather than sharing the one the console answers
    -- on: a leak here must not be able to repoint the console.
    dns_credential_sealed TEXT,
    -- Staging and production are different ACME accounts with different rate limits, and pointing
    -- a fleet at the wrong one is silent — staging certificates are well-formed and simply not
    -- trusted. Stored per domain so a new domain can be brought up against staging while the
    -- fleet's real domain keeps issuing for real.
    acme_directory TEXT NOT NULL,
    acme_contact TEXT,
    -- The ACME account is per domain, not per node: one account issuing for one domain is what
    -- lets the control plane serialize orders and stay under the rate limits, which N independent
    -- accounts could not coordinate.
    acme_account_key_sealed TEXT,
    acme_account_url TEXT,
    -- Public certificates normally last 90 days; self-signed certificates last a year. The advance window
    -- is retry time before either kind breaks, not merely a countdown for display.
    renew_before_days INTEGER DEFAULT 30 NOT NULL,
    created_at TIMESTAMPTZ DEFAULT now() NOT NULL,
    CONSTRAINT cert_domains_pkey PRIMARY KEY (id),
    CONSTRAINT cert_domains_domain_key UNIQUE (domain),
    CONSTRAINT cert_domains_domain_shape CHECK ((domain ~ '^[a-z0-9]([a-z0-9-]*[a-z0-9])?(\.[a-z0-9]([a-z0-9-]*[a-z0-9])?)+$')),
    CONSTRAINT cert_domains_provider_known CHECK ((dns_provider = 'cloudflare')),
    -- An https URL, or the one name that means nobody signs it but us. Spelled out rather than
    -- loosened to "any non-empty string": a typo in this column points the fleet at a CA that does
    -- not exist, and the failure surfaces one node at a time, half an hour apart.
    CONSTRAINT cert_domains_directory_shape CHECK ((acme_directory ~ '^https://' OR acme_directory = 'self-signed')),
    CONSTRAINT cert_domains_renew_before_range CHECK (((renew_before_days >= 1) AND (renew_before_days <= 89)))
);

