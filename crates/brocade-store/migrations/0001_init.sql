-- A node's periodic observations: credentials, versions, local reconcile results, reporting backlog,
-- and the on-disk state of the rule databases.
--
-- Its own table apart from node_applied_state, because nothing here appears in any artifact.
-- Artifact reconciliation compares what the control plane sent and is written only when the agent
-- reports a convergence result; these were never sent by it and are reported through
-- `/agent/v1/runtime` every 30 seconds. Hung off release observations, a machine that does not ship
-- for a month leaves all of this unknown for a month — exactly the failure these columns exist to
-- prevent.
--
-- Versions — `geodata` auto-update landed on xray's main branch only on 2026-04-25, and earlier
-- versions silently ignore that section. Without a version column, "this machine's .dat never
-- updates" and "the network cannot reach the download source" look identical. The two `wg` fields
-- matter more: wireguard-tools is installed by the install script through the distribution's package
-- manager and the control plane has no expectation at all; below 1.0.20200121 there is no
-- `wg syncconf`, and the repair ladder loses its only rung that does not interrupt sessions. Kernel
-- versus userspace decides the order of magnitude of throughput, and their `wg show` output is
-- identical.
--
-- Local reconcile — `reconcile_local` runs precisely when the control plane answers 204 (nothing
-- being released), and without this column "the machine drifted and repaired itself" happens
-- entirely without the control plane's knowledge.
--
-- Backlog — while the agent cannot reach the control plane it accumulates reports in a spool,
-- dropping the oldest past the limit. What is dropped is accounting, and the symptom is "this machine
-- had no traffic this month", indistinguishable from genuinely having none. `dropped` only grows:
-- non-zero means accounting was permanently lost.
--
-- geodata_observed — the actual on-disk state of geoip.dat / geosite.dat on each machine. Those two
-- .dat files are not sent by the control plane; xray downloads them on its own cron, and all the
-- control plane can expect is that the config says to update, with landing beyond its say. So what is
-- stored here are observed facts rather than a state judgement: how large the file is, when its mtime
-- is, which copy its sha256 identifies, and which directory it was read from. Whether an update
-- landed is judged from mtime and whether the nodes share one copy from sha256 — two questions need
-- two fields, and storing one answers neither fully. Reconciliation is required because xray's
-- `app/geodata/download.go` rolls back and keeps the old file on a failed download without erroring
-- or retrying to the control plane: without this column, a machine three months without a successful
-- update looks in the UI exactly like one succeeding daily.
--
-- An empty object means not yet observed, which must stay apart from "the file does not exist". The
-- first means its turn has not come and the second is a real problem. So on upsert an agent
-- reporting None keeps the old value rather than overwriting it with empty.
CREATE TABLE IF NOT EXISTS node_agent_state (
    node_id TEXT NOT NULL,
    token_hash TEXT,
    token_prefix TEXT,
    token_created_at TIMESTAMPTZ,
    token_last_used_at TIMESTAMPTZ,
    token_revoked_at TIMESTAMPTZ,
    agent_version TEXT,
    -- The binary identity answers "which bytes"; this answers whether those bytes can safely consume
    -- the desired-state wire contract. NULL is an agent that never sent the header.
    agent_protocol_version INTEGER,
    last_poll_at TIMESTAMPTZ,
    last_usage_report_at TIMESTAMPTZ,
    xray_started_at TIMESTAMPTZ,
    route_ipv4 TEXT,
    route_ipv6 TEXT,
    runtime_versions JSONB DEFAULT '{}'::jsonb NOT NULL,
    last_local_reconcile JSONB,
    wireguard_health JSONB DEFAULT '{}'::jsonb NOT NULL,
    spool_backlog JSONB DEFAULT '{}'::jsonb NOT NULL,
    runtime_reported_at TIMESTAMPTZ,
    geodata_observed JSONB DEFAULT '{}'::jsonb NOT NULL,
    -- The slow-moving half of the load report: kernel, cores, RAM and disk capacity, congestion
    -- algorithm, qdisc, whether we own this machine's sysctl. Latest only.
    --
    -- Here rather than in node_load_samples because none of it belongs in a 30-second series, and
    -- here rather than in its own table because that is exactly what runtime_versions,
    -- geodata_observed and spool_backlog already are — one JSONB blob per machine holding the
    -- latest observation of something the control plane did not send. A fourth table for the
    -- fourth such blob would be the odd one out.
    --
    -- NULL means no load report has ever arrived: either a freshly enrolled machine, or an agent
    -- from before this feature. The console has to say which in words; rendered as zeros it looks
    -- like a machine sitting idle, which is the one reading it must never produce.
    load_host_facts JSONB,
    load_reported_at TIMESTAMPTZ,
    -- The reporting agent's clock minus the control plane's, in seconds, signed. It can only be
    -- measured when a report arrives (read_at reads the agent's clock, which is gone afterwards),
    -- so it is stored here rather than recomputed. Load is ephemeral and still rejects ±600s;
    -- durable usage replay has its own sequence/epoch protocol and allows past readings.
    load_clock_skew_secs BIGINT,
    -- The generation last acknowledged as converged on this machine, plus the exact outcome of
    -- the latest usage ingestion round. Both are operational state, never model state.
    usage_generation_id BIGINT,
    usage_last_result JSONB DEFAULT '{}'::jsonb NOT NULL,
    CONSTRAINT node_agent_state_pkey PRIMARY KEY (node_id),
    CONSTRAINT node_agent_state_token_hash_key UNIQUE (token_hash),
    CONSTRAINT node_agent_state_node_id_fkey FOREIGN KEY (node_id) REFERENCES nodes(id) ON DELETE RESTRICT
);

