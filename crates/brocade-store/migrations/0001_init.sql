-- The control plane's complete schema, creating a database from nothing.
--
-- This is the only migration. Backward compatibility is not maintained during development —
-- changing the schema means editing this file and rebuilding the database.
--
-- Every statement below is idempotent, so applying this file to a database that already carries
-- the schema is a no-op instead of an error. That is not for the schema's sake but for the
-- checksum's: sqlx hashes this file's contents and refuses to start when the hash differs from the
-- one recorded in `_sqlx_migrations`, and editing so much as a comment changes the hash. Without
-- idempotency the only way out of that mismatch is to drop the database, which costs whatever was
-- in it — a running control plane loses its operators, nodes and revisions over a reworded comment.
-- With it, the recovery is to clear `_sqlx_migrations` and restart: this file re-applies harmlessly
-- and the new checksum is recorded.
--
-- What idempotency here does not do: `IF NOT EXISTS` skips an existing table without checking that
-- it matches what is written here. A real schema change therefore still means rebuilding the
-- database — this only makes re-applying an *unchanged* schema safe.

CREATE OR REPLACE FUNCTION brocade_valid_reality_short_ids(value JSONB) RETURNS BOOLEAN
    LANGUAGE sql IMMUTABLE STRICT
    AS $_$
    SELECT jsonb_typeof(value) = 'array'
        AND jsonb_array_length(value) > 0
        AND NOT EXISTS (
            SELECT 1
            FROM jsonb_array_elements(value) AS item(element)
            WHERE jsonb_typeof(item.element) <> 'string'
                OR item.element #>> '{}' !~ '^(?:[0-9A-Fa-f]{2}){1,8}$'
        )
$_$;

CREATE OR REPLACE FUNCTION brocade_valid_tenant_path(value TEXT) RETURNS BOOLEAN
    LANGUAGE sql IMMUTABLE STRICT
    AS $_$
    SELECT value ~ '^[a-z0-9_-]{1,32}(\.[a-z0-9_-]{1,32})*$'
$_$;

CREATE OR REPLACE FUNCTION brocade_valid_xhttp_download(value JSONB) RETURNS BOOLEAN
    LANGUAGE sql IMMUTABLE STRICT
    AS $_$
    SELECT jsonb_typeof(value) = 'object'
        AND jsonb_typeof(value -> 'host') = 'string'
        AND btrim(value ->> 'host') <> ''
        AND jsonb_typeof(value -> 'port') = 'number'
        AND (value ->> 'port')::INTEGER BETWEEN 1 AND 65535
        AND (
            NOT (value ? 'http_host')
            OR (
                jsonb_typeof(value -> 'http_host') = 'string'
                AND btrim(value ->> 'http_host') <> ''
            )
        )
        AND (
            NOT (value ? 'mux')
            OR (
                jsonb_typeof(value -> 'mux') = 'number'
                AND (value ->> 'mux')::INTEGER BETWEEN 2 AND 128
            )
        )
$_$;

