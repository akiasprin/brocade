    "overlay" BOOLEAN DEFAULT true NOT NULL,
    egress_allowed BOOLEAN DEFAULT false NOT NULL,
    dns_kind TEXT NOT NULL,
    dns_servers JSONB DEFAULT '[]'::jsonb NOT NULL,
    created_at TIMESTAMPTZ DEFAULT now() NOT NULL,
    created_revision BIGINT,
    retired_at TIMESTAMPTZ,
    mtu INTEGER,
    wg_transport JSONB DEFAULT '{"t": "udp"}'::jsonb NOT NULL,
    public_ipv6 TEXT,
    public_ipv4_nat BOOLEAN DEFAULT false NOT NULL,
    public_ipv6_nat BOOLEAN DEFAULT false NOT NULL,
