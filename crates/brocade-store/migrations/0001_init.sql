CREATE FUNCTION brocade_valid_reality_short_ids(value JSONB) RETURNS BOOLEAN
    LANGUAGE sql IMMUTABLE STRICT
    AS $_$
    SELECT jsonb_typeof(value) = 'array'
        AND jsonb_array_length(value) > 0
        AND NOT EXISTS (
            SELECT 1
            FROM jsonb_array_elements(value) AS item(element)
            WHERE jsonb_typeof(item.element) <> 'string'
                OR item.element #>> '{}' !~ '^(?:[0-9A-Fa-f]{2}){1,8}$'
        )
$_$;

CREATE FUNCTION brocade_valid_tenant_path(value TEXT) RETURNS BOOLEAN
    LANGUAGE sql IMMUTABLE STRICT
    AS $_$
    SELECT value ~ '^[a-z0-9_-]{1,32}(\.[a-z0-9_-]{1,32})*$'
$_$;

CREATE FUNCTION brocade_valid_xhttp_download(value JSONB) RETURNS BOOLEAN
    LANGUAGE sql IMMUTABLE STRICT
    AS $_$
    SELECT jsonb_typeof(value) = 'object'
        AND jsonb_typeof(value -> 'host') = 'string'
        AND btrim(value ->> 'host') <> ''
        AND jsonb_typeof(value -> 'port') = 'number'
        AND (value ->> 'port')::INTEGER BETWEEN 1 AND 65535
        AND (
            NOT (value ? 'http_host')
            OR (
                jsonb_typeof(value -> 'http_host') = 'string'
                AND btrim(value ->> 'http_host') <> ''
            )
        )
        AND (
            NOT (value ? 'mux')
            OR (
                jsonb_typeof(value -> 'mux') = 'number'
                AND (value ->> 'mux')::INTEGER BETWEEN 2 AND 128
            )
        )
$_$;

