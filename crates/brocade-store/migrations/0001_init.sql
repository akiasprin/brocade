-- One release.
--
-- sync_of_deployment_id: after a release is cancelled, where targets have already succeeded, failed
-- into dirty, or been dispatched without reporting, the control plane creates an ordinary deployment
-- as a state-synchronization order, and this FK records which cancellation it came from.
--
-- kind splits deployments into two: configuration and grants. The reason is not tidiness but that
-- the two differ in cost by an order of magnitude: configuration lands on disk and restarts a
-- process or reconnects a tunnel; grants merely add to or remove from the list inside a running xray
-- over an API, with the process untouched.
--
-- Mixed into one deployment, a grant change would restart xray along the way. The agent converges on
-- the desired state without looking at actions (converge_linux in main.rs), and an xray that is
-- Present in desired gets an unconditional restart even where the deployment changes one person's
-- grant, so "changing a grant drops nobody" would not hold. The narrowing happens at the plan layer
-- (narrow_to_kind in brocade-deployment): a grants deployment marks phantun, wireguard, and xray all
-- Unmanaged, and the agent's converge_linux_* returns on seeing Unmanaged. That is harder than a
-- runtime check in the control plane — it is not "remember not to push configuration" but that there
-- is no configuration in that deployment to push.
--
-- base_revision_id is the "from" in "changed from which version to which". The console shows which
-- artifact lines each release changed, and artifacts are a pure function of the snapshot
-- (console.rs::artifact_index_of), so compiling two revisions and comparing line by line suffices —
-- all that is missing is which version was the previous one.
--
-- It is not derived at query time by scanning back for status='succeeded', because a rollback
-- scrambles that timeline: after a rollback succeeds the machines run an older revision, a backward
-- scan thereafter finds that rollback as the last success, and that is not what was seen at
-- creation. A baseline computed after the fact is not the baseline the release used, and the diff
-- then shows a pile of changes that never belonged to it. Fixed at creation and never changed
-- afterwards is the only convention that cannot contradict itself.
--
-- Computed per kind, on the same reasoning as holding the single-flight lock per kind: what lands on
-- disk is decided by the last successful configuration deployment and the runtime list by the last
-- successful grants deployment, and the two lines do not interfere.
--
-- NULL has a precise meaning: this kind has never shipped successfully and there is no previous
-- version to compare. Marking every artifact as changed on a first release says nothing, and the UI
-- shows contents without a diff as usual.
CREATE TABLE deployments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    revision_id BIGINT NOT NULL,
    status TEXT NOT NULL,
    created_at TIMESTAMPTZ DEFAULT now() NOT NULL,
    started_at TIMESTAMPTZ,
    halted_at TIMESTAMPTZ,
    finished_at TIMESTAMPTZ,
    actor TEXT,
    idempotency_key TEXT,
    active BOOLEAN,
    warnings JSONB DEFAULT '[]'::jsonb NOT NULL,
    rollback_of_deployment_id BIGINT,
    divergence_cleared_at TIMESTAMPTZ,
    note TEXT,
    sync_of_deployment_id BIGINT,
    kind TEXT DEFAULT 'config' NOT NULL,
    base_revision_id BIGINT,
    -- status/active tracks execution. Activation answers whether this revision is serving;
    -- settlement answers whether every node has converged or some isolated node still owes the
    -- latest desired state.
    activation_status TEXT DEFAULT 'waiting' NOT NULL,
    settlement_status TEXT DEFAULT 'converged' NOT NULL,
    activated_at TIMESTAMPTZ,
    CONSTRAINT deployments_activation_status_check CHECK ((activation_status IN ('waiting', 'activated', 'rejected'))),
    CONSTRAINT deployments_settlement_status_check CHECK ((settlement_status IN ('converged', 'debt', 'uncertain'))),
    CONSTRAINT deployments_kind_check CHECK ((kind IN ('config', 'grants'))),
    CONSTRAINT deployments_status_check CHECK ((status IN ('planned', 'running', 'halted', 'succeeded', 'failed', 'canceled'))),
    CONSTRAINT deployments_warnings_check CHECK ((jsonb_typeof(warnings) = 'array')),
    CONSTRAINT deployments_idempotency_key_key UNIQUE (idempotency_key),
    CONSTRAINT deployments_pkey PRIMARY KEY (id),
    CONSTRAINT deployments_base_revision_id_fkey FOREIGN KEY (base_revision_id) REFERENCES revisions(id),
    CONSTRAINT deployments_revision_id_fkey FOREIGN KEY (revision_id) REFERENCES revisions(id),
    CONSTRAINT deployments_rollback_of_deployment_id_fkey FOREIGN KEY (rollback_of_deployment_id) REFERENCES deployments(id),
    CONSTRAINT deployments_sync_of_deployment_id_fkey FOREIGN KEY (sync_of_deployment_id) REFERENCES deployments(id)
);


