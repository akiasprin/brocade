-- Per-hop line quality, aggregated from the TCP connections actually carrying that hop.
--
-- The numbers come from netlink inet_diag (tcp_info + tcp_bbr_info) on the node. They are free:
-- BBR keeps a bottleneck-bandwidth and min-RTT estimate on every real forwarding connection and
-- updates it every RTT, so nothing extra is sent on the wire. The two probe tables next door are
-- both active measurements — link_probes pings for path MTU every 30 minutes, e2e_probes fetches
-- through the chain every 5 — which is why neither can answer "which hop is the bottleneck right
-- now": their traffic is not the users' traffic.
--
-- Keyed (chain_id, peer_node_id), the same key link_health uses, because it measures the same
-- thing: this machine's outbound leg towards its next hop. The agent derives the pair from xray's
-- outbound tags (`out:{app}/{chain}>{to}`), which is machinery it already has.
--
-- Deliberately NOT usage_chain_samples' hop_label. That label is steps.accept_label, an inbound
-- identity: on the leg hk-01 → sg-02 it belongs to sg-02 while the measurement happens on hk-01,
-- so the two never share a node_id and joining on it lines up rows about different machines.
--
-- Byte counts are absent for the same reason: link_health already holds this hop's downlink for
-- this window, from the same agent in the same round. The console reads both.
--
-- No foreign key on chain_id, for the reason usage_samples gives at length: a rollback DELETEs and
-- rebuilds chains from the snapshot, and a sample is a historical fact that must not require the
-- model object to still exist.
--
-- btlbw is nullable and that is the interesting case rather than a defect: cubic keeps no
-- bottleneck-bandwidth estimate at all. A NULL here means "this machine cannot measure", which is
-- the second argument for forcing BBR on — not only to go faster, but to be able to see.
CREATE TABLE node_hop_link_samples (
    node_id TEXT NOT NULL,
    chain_id TEXT NOT NULL,
    peer_node_id TEXT NOT NULL,
    window_start TIMESTAMPTZ NOT NULL,
    window_end TIMESTAMPTZ NOT NULL,
    conns INTEGER NOT NULL,
    -- Of `conns`, those whose delivery_rate did not carry the app_limited flag. Only these feed
    -- the bandwidth percentiles: a connection with nothing to send measures the application, not
    -- the line, and unfiltered a few idle ones drag the estimate to the floor.
    conns_measured INTEGER NOT NULL,
    btlbw_p50_bps BIGINT,
    btlbw_p90_bps BIGINT,
    min_rtt_us INTEGER NOT NULL,
    rtt_p50_us INTEGER NOT NULL,
    rtt_p90_us INTEGER NOT NULL,
    retrans_pct REAL NOT NULL,
    busy_pct REAL NOT NULL,
    rwnd_limited_pct REAL NOT NULL,
    sndbuf_limited_pct REAL NOT NULL,
    CONSTRAINT node_hop_link_samples_window CHECK ((window_end > window_start)),
    CONSTRAINT node_hop_link_samples_conns CHECK (((conns >= 0) AND (conns_measured >= 0) AND (conns_measured <= conns))),
    CONSTRAINT node_hop_link_samples_bw CHECK ((((btlbw_p50_bps IS NULL) OR (btlbw_p50_bps >= 0)) AND ((btlbw_p90_bps IS NULL) OR (btlbw_p90_bps >= 0)))),
    -- Percentages are shares of one window and cannot exceed it. Catching a broken aggregation
    -- here rather than in the UI matters because the UI draws these as bar widths: a 3000% share
    -- renders as a full bar, indistinguishable from a real saturation.
    CONSTRAINT node_hop_link_samples_pct CHECK (((retrans_pct >= 0) AND (retrans_pct <= 100) AND (busy_pct >= 0) AND (busy_pct <= 100) AND (rwnd_limited_pct >= 0) AND (rwnd_limited_pct <= 100) AND (sndbuf_limited_pct >= 0) AND (sndbuf_limited_pct <= 100))),
    CONSTRAINT node_hop_link_samples_pkey PRIMARY KEY (node_id, chain_id, peer_node_id, window_start),
    CONSTRAINT node_hop_link_samples_node_id_fkey FOREIGN KEY (node_id) REFERENCES nodes(id) ON DELETE CASCADE,
    -- The peer is a live machine, unlike chain_id: link_health carries the same reference and the
    -- same CASCADE. A leg towards a deleted machine describes nothing.
    CONSTRAINT node_hop_link_samples_peer_node_id_fkey FOREIGN KEY (peer_node_id) REFERENCES nodes(id) ON DELETE CASCADE
);

-- One machine's resource use, one row per window.
--
-- The agent differences locally and sends rates; the control plane stores what it is given. That
-- is the opposite of usage, which sends cumulative counters and is differenced here — because
-- usage is money and has to be auditable and duplicate-proof, while a load reading is worthless once
-- stale and keeping a previous reading per machine would be paid for nothing.
--
-- What that costs is the control plane's ability to notice a counter reset by itself, which is why
-- btime is stored alongside: it changes exactly when the machine rebooted and every cumulative
-- counter restarted. has_gap is the agent saying so for this window.
--
-- Slow-moving facts (kernel, cores, RAM size, disk capacity, conntrack_max, congestion algorithm)
-- are NOT here — they live in node_agent_state.load_host_facts. Writing a disk's capacity 2 880
-- times a day per machine buys nothing, and it would also be a lie about what the number is: a
-- disk does not have a size "during the window 12:00:30–12:01:00".
--
-- ON DELETE CASCADE rather than RESTRICT, unlike the usage tables: these rows are diagnostics, not
-- accounting, and a retired machine's CPU history is not worth blocking its deletion over.
CREATE TABLE node_load_samples (
    node_id TEXT NOT NULL,
    window_start TIMESTAMPTZ NOT NULL,
    window_end TIMESTAMPTZ NOT NULL,
    btime BIGINT NOT NULL,
    has_gap BOOLEAN DEFAULT false NOT NULL,
    -- Three parts, never summed on the way in. Forwarding load lands on softirq, and once summed
    -- "the NIC's interrupts saturated a core" is indistinguishable from "xray is encrypting" —
    -- while one wants multi-queue or a bigger machine and the other wants traffic moved elsewhere.
    cpu_user_pct REAL NOT NULL,
    cpu_sys_pct REAL NOT NULL,
    cpu_softirq_pct REAL NOT NULL,
    -- The largest sub-sample inside the window. Averages erase spikes, and spikes are what
    -- forwarding load is made of.
    cpu_peak_pct REAL NOT NULL,
    -- /proc/stat's steal: the share of CPU time this machine wanted but the hypervisor gave to
    -- another guest. Not summed into the three shares above — steal is not work this machine
    -- does; a sustained non-zero value means an oversold host.
    cpu_steal_pct REAL NOT NULL,
    load1 REAL NOT NULL,
    -- Optional deep diagnostics. JSONB keeps one atomic observation together
    -- (including a variable-length per-core list) without turning this hot time-series table into
    -- dozens of sparse columns. NULL means the diagnostic was unavailable, never a zero reading.
    cpu_detail JSONB,
    mem_available_bytes BIGINT NOT NULL,
    swap_used_bytes BIGINT NOT NULL,
    memory_detail JSONB,
    oom_kills BIGINT NOT NULL,
    disk_free_bytes BIGINT NOT NULL,
    disk_inode_free_pct REAL NOT NULL,
    -- Optional rates/latency for the block device backing the agent state filesystem. NULL is an
    -- overlay/network filesystem without a local block-device view, never an idle disk.
    disk_detail JSONB,
    nic_rx_bps BIGINT NOT NULL,
    nic_tx_bps BIGINT NOT NULL,
    nic_rx_drop BIGINT NOT NULL,
    nic_tx_drop BIGINT NOT NULL,
    nic_err BIGINT NOT NULL,
    -- NULL means nf_conntrack is not loaded, which is not a fault: a machine doing no NAT has no
    -- such table. Storing 0 instead would read as "the table is empty", and an empty table on a
    -- busy NAT node is a real and different alarm.
    conntrack_count BIGINT,
    -- Optional socket inventory and differenced TCP/UDP MIB counters from newer agents. As with
    -- CPU and memory detail, one atomic JSONB object keeps the hot series narrow and NULL means
    -- "unavailable kernel view", never an all-zero network.
    network_detail JSONB,
    uptime_secs BIGINT NOT NULL,
    CONSTRAINT node_load_samples_window CHECK ((window_end > window_start)),
    -- CPU shares are normalised across all cores, so each part is within a window and the three
    -- together cannot exceed it. load1 deliberately has no upper bound — it is a queue length, not
    -- a share, and on an overloaded 2-core box 30 is a real reading.
    CONSTRAINT node_load_samples_cpu CHECK (((cpu_user_pct >= 0) AND (cpu_sys_pct >= 0) AND (cpu_softirq_pct >= 0) AND (cpu_peak_pct >= 0) AND (cpu_peak_pct <= 100) AND ((cpu_user_pct + cpu_sys_pct + cpu_softirq_pct) <= 100.5) AND (cpu_steal_pct >= 0) AND (cpu_steal_pct <= 100))),
    CONSTRAINT node_load_samples_load CHECK ((load1 >= 0)),
    CONSTRAINT node_load_samples_bytes CHECK (((mem_available_bytes >= 0) AND (swap_used_bytes >= 0) AND (disk_free_bytes >= 0) AND (nic_rx_bps >= 0) AND (nic_tx_bps >= 0))),
    CONSTRAINT node_load_samples_counts CHECK (((oom_kills >= 0) AND (nic_rx_drop >= 0) AND (nic_tx_drop >= 0) AND (nic_err >= 0) AND (uptime_secs >= 0) AND ((conntrack_count IS NULL) OR (conntrack_count >= 0)))),
    CONSTRAINT node_load_samples_inode CHECK (((disk_inode_free_pct >= 0) AND (disk_inode_free_pct <= 100))),
    CONSTRAINT node_load_samples_pkey PRIMARY KEY (node_id, window_start),
    CONSTRAINT node_load_samples_node_id_fkey FOREIGN KEY (node_id) REFERENCES nodes(id) ON DELETE CASCADE
);

