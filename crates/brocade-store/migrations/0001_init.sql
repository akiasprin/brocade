CREATE TABLE IF NOT EXISTS ingresses (
    id TEXT NOT NULL,
    app_id TEXT NOT NULL,
    chain_id TEXT NOT NULL,
    node_id TEXT NOT NULL,
    bind INET NOT NULL,
    port INTEGER NOT NULL,
    front_id TEXT,
    -- The whole shape of the wire: protocol, security layer and network layer named as one
    -- verified combination rather than as independent axes. 'vless-reality' is one TCP connection
    -- per client connection; 'vless-reality-xhttp' carries many streams inside one HTTP/2
    -- connection, which collapses the per-connection REALITY handshake — and with it the dial to
    -- the borrowed site that each handshake costs.
    --
    -- Named together because the axes are not independent: Vision flow control over XHTTP builds
    -- clean, passes `xray -test`, and refuses every connection at runtime.
    -- The TCP half, or NULL where this ingress serves QUIC only. Nullable because an ingress may
    -- carry either wire or both, and "both" is the point: one credential, one grant, two
    -- listeners, and a client that takes whichever gets through.
    transport_kind TEXT,
    -- The UDP half. Separate from transport_kind rather than another value inside it: they are
    -- not alternatives, they coexist, and one column cannot hold two answers.
    hy2_enabled BOOLEAN DEFAULT FALSE NOT NULL,
    -- AnyTLS is another independent TCP listener. It may coexist with VLESS and Hysteria 2. Its
    -- protocol security identity and target are independent; only the business-level user grants
    -- belong to the common ingress.
    anytls_enabled BOOLEAN DEFAULT FALSE NOT NULL,
    anytls_security TEXT DEFAULT 'tls' NOT NULL,
    -- AnyTLS REALITY does not inherit the VLESS target on the same ingress. NULL means the global
    -- site; an object stores the protocol's own global/custom provenance and custom override.
    anytls_reality JSONB,
    -- Generated independently from the VLESS identity. Nullable only while AnyTLS has never been
    -- enabled; the write path fills all three columns together before REALITY can be published.
    anytls_reality_private_key TEXT,
    anytls_reality_public_key TEXT,
    anytls_reality_short_ids JSONB,
    anytls_port INTEGER,
    anytls_padding_scheme JSONB DEFAULT '[]'::jsonb NOT NULL,
    anytls_masquerade_kind TEXT DEFAULT '404' NOT NULL,
    anytls_masquerade_content TEXT DEFAULT '' NOT NULL,
    anytls_masquerade_headers JSONB DEFAULT '{}'::jsonb NOT NULL,
    anytls_masquerade_status_code INTEGER DEFAULT 200 NOT NULL,
    reality_private_key TEXT NOT NULL,
    reality_public_key TEXT NOT NULL,
    reality_short_ids JSONB NOT NULL,
    reality_dest TEXT,
    reality_server_names JSONB NOT NULL,
    reality_fingerprint TEXT,
    reality_flow TEXT,
    reality_fallback_mode TEXT DEFAULT 'global-site' NOT NULL,
    reality_fallback_limits JSONB DEFAULT '{"mode":"balanced"}'::jsonb NOT NULL,
    -- Whether an unauthenticated fallback may reach names other than the borrowed one. Default on:
    -- a borrowed site is usually somebody's CDN, whose address answers for its neighbours too, and
    -- REALITY hands the connection over before it has read which name was asked for.
    reality_fallback_guard BOOLEAN DEFAULT TRUE NOT NULL,
    -- The path is stored rather than derived from the ingress id: it is copied into every client
    -- configuration, so deriving it would make renaming an ingress silently disconnect everyone.
    xhttp_path TEXT,
    xhttp_host TEXT,
    -- The client-side XMUX policy. NULL means the whole object is absent, so Xray injects its
    -- versioned defaults. A present object is deliberately complete: Xray only injects
    -- hMaxRequestTimes=600-900 and hMaxReusableSecs=1800-3000 when every XMUX field is zero, so
    -- storing maxConcurrency alone silently turns both rotation limits into unlimited.
    xhttp_xmux JSONB,
    -- Request/response Padding. NULL means the key is omitted and Xray owns its versioned
    -- default; POST upload controls are intentionally not managed.
    xhttp_tuning JSONB,
    -- A REALITY + XHTTP independent download may terminate TLS on a separate local port. The
    -- public host/port and download HTTP Host remain client-only and live in
    -- ingress_client_settings; these two columns are the only part the node compiler needs.
    xhttp_download_v4_origin_port INTEGER,
    xhttp_download_v6_origin_port INTEGER,
    -- How the client sends its upload half. NULL is "nobody chose", and then both ends resolve it
    -- the same way on their own. A stored value is written into the server config too, where it
    -- stops being a choice and becomes a filter: a server told to expect one shape refuses every
    -- client that names another.
    xhttp_mode TEXT,
    -- The UDP wire's own port. NULL exactly when this ingress has no UDP wire: the port belongs
    -- to the wire, and a row without that wire has no port to hold. It used to reuse `port`,
    -- which was safe only while nothing claimed a range around it — see hy2_hop_* below.
    hy2_port INTEGER,
    -- The port-hopping range, inclusive, or NULL for "clients stay on hy2_port". Both ends are
    -- present or both absent; the range must contain hy2_port, because that is the only port the
    -- server actually binds — the rest reach it through the machine's redirect.
    hy2_hop_start INTEGER,
    hy2_hop_end INTEGER,
    hy2_up TEXT,
    hy2_down TEXT,
    hy2_congestion TEXT DEFAULT 'brutal' NOT NULL,
    -- BBR 策略。只在这条连接实际跑 BBR 时被读到（congestion 是 bbr，或者是 brutal
    -- 而带宽没填）。xray 把缺省当作 standard，所以这里也以 standard 为默认。
    hy2_bbr_profile TEXT DEFAULT 'standard' NOT NULL,
    -- finalmask.quicParams 里的调优项。全部可空，空 = 不写这个键，由 xray 用它自己那一版的
    -- 默认值。存我们以为的默认值会把今天的上游默认固化进产物，产物就不再跟着部署的版本走。
    -- 下面每条 CHECK 的边界都取自 xray 的构建期校验，越界会让它起不来。
    hy2_quic_init_stream_window BIGINT,
    hy2_quic_max_stream_window BIGINT,
    hy2_quic_init_conn_window BIGINT,
    hy2_quic_max_conn_window BIGINT,
    hy2_quic_max_idle_secs INTEGER,
    hy2_quic_keepalive_secs INTEGER,
    hy2_quic_max_incoming_streams INTEGER,
    hy2_quic_disable_pmtud BOOLEAN DEFAULT FALSE NOT NULL,
    hy2_obfs_password TEXT,
    hy2_masquerade_kind TEXT DEFAULT 'not-found' NOT NULL,
    hy2_masquerade_url TEXT,
    -- What this entrance refuses to carry, before anything its chain says. Five columns rather
    -- than one JSONB blob: each is a separate operator decision with its own default, and a blob
    -- would make "which of these is on" a question you have to parse to answer — including in the
    -- WHERE that decides whether a write changed anything.
    --
    -- Four default TRUE. They refuse what nobody knowingly wants: reaching the fleet's own overlay
    -- from outside, seeding torrents from a shared address, sending mail from an address that gets
    -- blacklisted for it, and bouncing amplification traffic off open UDP services. The fifth is
    -- FALSE because it takes games and voice with it.
    guard_no_private BOOLEAN DEFAULT TRUE NOT NULL,
    guard_no_bittorrent BOOLEAN DEFAULT TRUE NOT NULL,
    guard_no_mail BOOLEAN DEFAULT TRUE NOT NULL,
    guard_no_udp_amplification BOOLEAN DEFAULT TRUE NOT NULL,
    guard_tcp_and_quic_only BOOLEAN DEFAULT FALSE NOT NULL,
    -- The outward projection: the address written in subscriptions. One pair per family, with NULL
    -- meaning that family is not projected. See brocade_core::model::Projection.
    projection_v4_host TEXT,
    projection_v4_port INTEGER,
    projection_v4_download_host TEXT,
    projection_v4_download_port INTEGER,
    projection_v4_download_origin_port INTEGER,
    projection_v4_download_http_host TEXT,
    projection_v4_download_mux INTEGER,
    projection_v6_host TEXT,
    projection_v6_port INTEGER,
    projection_v6_download_host TEXT,
    projection_v6_download_port INTEGER,
    projection_v6_download_origin_port INTEGER,
    projection_v6_download_http_host TEXT,
    projection_v6_download_mux INTEGER,
    created_at TIMESTAMPTZ DEFAULT now() NOT NULL,
    created_revision BIGINT,
    CONSTRAINT ingresses_port_check CHECK (((port >= 1) AND (port <= 65535))),
    -- xhttp without a path is an ingress no client can reach: the path is what the server matches
    -- a request against, and a mismatch is refused outright (`failed to validate path`).
    CONSTRAINT ingresses_xhttp_path CHECK (((transport_kind IS NULL OR transport_kind NOT IN ('vless-reality-xhttp', 'vless-tls-xhttp')) OR (xhttp_path ~ '^/'))),
    CONSTRAINT ingresses_xhttp_host_check CHECK ((xhttp_host IS NULL) OR (btrim(xhttp_host) <> '')),
    CONSTRAINT ingresses_xhttp_xmux_shape CHECK (
        xhttp_xmux IS NULL OR ((
            jsonb_typeof(xhttp_xmux) = 'object'
            AND ((
                jsonb_typeof(xhttp_xmux -> 'max_concurrency') = 'number'
                AND (xhttp_xmux ->> 'max_concurrency')::INTEGER BETWEEN 1 AND 128
                AND NOT (xhttp_xmux ? 'max_connections')
            ) OR (
                jsonb_typeof(xhttp_xmux -> 'max_connections') = 'number'
                AND (xhttp_xmux ->> 'max_connections')::INTEGER BETWEEN 1 AND 128
                AND NOT (xhttp_xmux ? 'max_concurrency')
            ))
            AND jsonb_typeof(xhttp_xmux -> 'h_max_request_times') = 'object'
            AND jsonb_typeof(xhttp_xmux -> 'h_max_request_times' -> 'from') = 'number'
            AND jsonb_typeof(xhttp_xmux -> 'h_max_request_times' -> 'to') = 'number'
            AND (xhttp_xmux -> 'h_max_request_times' ->> 'from')::BIGINT BETWEEN 1 AND 2147483647
            AND (xhttp_xmux -> 'h_max_request_times' ->> 'to')::BIGINT BETWEEN 1 AND 2147483647
            AND (xhttp_xmux -> 'h_max_request_times' ->> 'from')::BIGINT
                <= (xhttp_xmux -> 'h_max_request_times' ->> 'to')::BIGINT
            AND jsonb_typeof(xhttp_xmux -> 'h_max_reusable_secs') = 'object'
            AND jsonb_typeof(xhttp_xmux -> 'h_max_reusable_secs' -> 'from') = 'number'
            AND jsonb_typeof(xhttp_xmux -> 'h_max_reusable_secs' -> 'to') = 'number'
            AND (xhttp_xmux -> 'h_max_reusable_secs' ->> 'from')::BIGINT BETWEEN 1 AND 2147483647
            AND (xhttp_xmux -> 'h_max_reusable_secs' ->> 'to')::BIGINT BETWEEN 1 AND 2147483647
            AND (xhttp_xmux -> 'h_max_reusable_secs' ->> 'from')::BIGINT
                <= (xhttp_xmux -> 'h_max_reusable_secs' ->> 'to')::BIGINT
            AND (
                NOT (xhttp_xmux ? 'h_keep_alive_period_secs')
                OR (
                    jsonb_typeof(xhttp_xmux -> 'h_keep_alive_period_secs') = 'number'
                    AND ((xhttp_xmux ->> 'h_keep_alive_period_secs')::INTEGER = -1
                        OR (xhttp_xmux ->> 'h_keep_alive_period_secs')::INTEGER BETWEEN 1 AND 3600)
