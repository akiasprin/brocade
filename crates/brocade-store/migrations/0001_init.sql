    xray_observed JSONB DEFAULT '{}'::jsonb NOT NULL,
    grants_state TEXT NOT NULL,
    grants_observed JSONB DEFAULT '{}'::jsonb NOT NULL,
    source_deployment_id BIGINT,
    observed_at TIMESTAMPTZ NOT NULL,
    phantun_state TEXT DEFAULT 'unknown' NOT NULL,
    phantun_sha256 TEXT,
    phantun_observed JSONB,
    -- Hysteria 2 跳转段的 nft 规则。**不是** control_state.port_hop_base 那个东西——那个是中转口
    -- 往上找空位的起点，跟 Hysteria 2 无关，只是名字里也有 hop。
