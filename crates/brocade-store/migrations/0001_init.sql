-- One machine. overlay is whether it joins the wg overlay; a relay port's shape is not here but on
-- steps.
--
-- retired_at is decommissioning, not disappearance. A marked machine stays in the snapshot, the
-- compiler produces "all three artifacts Disabled" for it, and the agent tears wg0 and xray down on
-- convergence and reports confirmation. Deleting it from the model outright has plan_deployment,
-- which walks the snapshot's nodes, find no target, the agent receive 204 forever, and local
-- reconcile replay it round after round from the old artifacts in state_dir — wg0 up, xray running,
-- the user allow-list intact, every credential valid, and the control plane wholly unaware it
-- exists.
--
-- retired_at rather than reusing users' status: users' disabled means suspended (for non-payment and
-- the like, and they come back), which is a state; a node's is present or absent only, and it also
-- wants the time recorded.
--
-- MTU is node-level: one machine has one wg0 and one MTU, `MTU =` appears only in wireguard.conf's
-- [Interface] section, and [Peer] has no such key at all. That is, "this link's MTU" is not a
-- configurable thing in WireGuard — giving different peers different MTUs requires an interface per
-- peer. A machine leaving it null takes control_state.overlay_mtu; it is not filled in per machine
-- because in the vast majority of deployments every machine really does use one number, and filling
-- it in per machine only means editing N places without adding any information.
--
-- wg_transport is WireGuard's inbound transport: plain UDP, or fake TCP through phantun.
--
-- WireGuard is UDP only, with no TCP mode. When an upstream seals inbound UDP (measured once: in
-- traceroute, ICMP and TCP reached hop 9 while UDP died at hop 8; having that machine dial out
-- brought no reply either, indicating a stateless block against which dial direction, keepalives,
-- and the like are all useless), the only way out is to wrap the UDP in something else at both ends.
-- phantun rather than a real TCP tunnel (wstunnel and the like): it merely wears a TCP disguise and
-- does neither retransmission nor congestion control, so there is no TCP-over-TCP meltdown where the
-- two layers amplify each other under loss.
--
-- Stored as jsonb rather than split into columns: the variants carry different material (udp carries
-- nothing, fake_tcp carries a port), and split into columns that is a field non-null under one
-- variant only. The shape is defined by model::WgTransport's serde (tag=t / content=v). The CHECK
-- only blocks dirty data such as an unheard-of t, and whether a variant's material is complete is
-- reported by serde on deserialization, which reports it more clearly than a CHECK could.
--
-- It states how others dial me, not how I dial others. Hence per node rather than per link — a
-- machine's entrance has one shape and everyone dialing it must agree.
--
-- The fake-TCP port must be a high one. 443 is not offered: that port is very likely already taken
-- by an ingress on this machine, and running something that is not TLS on 443 gives itself away to
-- the first active probe. Below 1024 likewise, all of them spoken for.
--
-- `domain_strategy` is how this machine's egress turns a domain into an address, and it sits beside
-- `dns_kind` / `dns_servers` because "which resolver to ask" and "which family to accept" are the
-- same axis. Its default reproduces the value the artifact layer used to hard-code, so an existing
-- row keeps its behaviour without being touched. A plain TEXT rather than jsonb: unlike
-- `wg_transport` every variant carries the same material, namely nothing, so a CHECK against the
-- known set is the whole of the validation.
