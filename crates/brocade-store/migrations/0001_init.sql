-- Port uniqueness, once per protocol. It used to be one constraint over a generated
-- `transport_protocol` column, which worked while an ingress was one wire or the other; a row
-- that carries both belongs in two buckets at once and no single column can say so. Two partial
-- indexes say it exactly: the TCP half is unique among TCP halves, the UDP half among UDP ones,
-- and one number can legitimately be both (that is how a two-wire ingress shares a port).
CREATE UNIQUE INDEX IF NOT EXISTS ingresses_tcp_port_key
    ON ingresses USING btree (node_id, port) WHERE transport_kind IS NOT NULL;
-- The UDP half is unique among UDP halves on its own column now that it has one. Nothing here
-- covers a hop range: the range is a redirect, not a bind, and two ingresses whose ranges overlap
-- is a compile-time diagnostic (`node.port-clash`) rather than something a unique index can state
-- — an index constrains rows, and a range is not a row.
CREATE UNIQUE INDEX IF NOT EXISTS ingresses_udp_port_key
    ON ingresses USING btree (node_id, hy2_port) WHERE hy2_enabled;

