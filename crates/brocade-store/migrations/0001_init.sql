    CONSTRAINT ingresses_anytls_port_present CHECK ((anytls_port IS NOT NULL) = anytls_enabled),
    CONSTRAINT ingresses_anytls_security_check CHECK (anytls_security IN ('tls', 'reality')),
    CONSTRAINT ingresses_anytls_reality_check CHECK (
        anytls_reality IS NULL
        OR (
            jsonb_typeof(anytls_reality) = 'object'
            AND anytls_reality ->> 'fallback_mode' IN ('global-site', 'custom-site')
