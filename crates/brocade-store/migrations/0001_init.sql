-- Per user × view traffic quotas.
--
-- The granularity matches usage.rs's `list_monthly_usage_summary` grouping key
-- (`GROUP BY s.tenant_id, s.user_id, app_id`): one quota row per consumption row, so "how much used"
-- and "how much allowed" need no reconciling of conventions.
--
-- It does not enter the model and therefore stamps no revision. A quota affects no artifact —
-- xray.json writes no users to begin with (argued in artifacts/xray.rs), and what writes users is
-- grants. Stamping a revision for every changed number would flood the release history while not one
-- byte of what ships changed. It is operational data, of a kind with admin_operators, written
-- directly. What really goes through the model is the action after a quota is spent (revoking that
-- view's grants), and a revision is stamped there, authored by `system:quota`.
--
-- app_id deliberately carries no foreign key even though it references apps.id: rolling back a
-- revision does a `DELETE FROM apps` and rebuilds wholesale (clear_app_model_tx in deployment.rs),
-- CASCADE would delete the quotas along with them, RESTRICT would block the rollback, and neither
-- route is available. The tenant/user pair can carry them — restore_users_tx goes through UPSERT and
-- those rows do not vanish. The cost is that quotas survive a deleted view as orphan rows, which the
-- read side filters against the current apps.
CREATE TABLE IF NOT EXISTS user_app_quotas (
    tenant_id TEXT NOT NULL,
    user_id TEXT NOT NULL,
    app_id TEXT NOT NULL,
    limit_bytes BIGINT NOT NULL,
    created_at TIMESTAMPTZ DEFAULT now() NOT NULL,
    updated_at TIMESTAMPTZ DEFAULT now() NOT NULL,
    CONSTRAINT user_app_quotas_limit_bytes_check CHECK ((limit_bytes > 0)),
    CONSTRAINT user_app_quotas_pkey PRIMARY KEY (tenant_id, user_id, app_id),
    CONSTRAINT user_app_quotas_tenant_id_user_id_fkey FOREIGN KEY (tenant_id, user_id) REFERENCES users(tenant_id, id) ON DELETE CASCADE
);

