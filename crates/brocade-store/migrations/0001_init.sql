-- The control plane's single-row global state.
--
-- The site REALITY borrows is global and an ingress's own columns are overrides: non-null takes the
-- ingress's, null takes the global one (materialize fills it in, in the same sense as "the model
-- layer permits blanks and filling in happens on the way to the IR").
--
-- The two overlay parameters are global rather than per node: links are computed from the full mesh
-- rather than written by hand, and per node would raise the unanswerable question of which value to
-- use when the two ends configured different ones.
--
-- The MTU floor is 1000 rather than 1280: 1280 is IPv6's minimum MTU while the overlay is IPv4 only
-- (Node.overlay_addr is an Ipv4Addr), so that constraint does not apply here; and effective tunnel
-- MTUs below 1280 genuinely occur on cross-border links (one measured at around 1258). A floor
-- exists to catch obvious misconfiguration: below 1000 TCP throughput collapses, and it is almost
-- certainly a typo.
--
-- The two port_*_base values are where automatic port selection starts. They are settings rather
-- than constants because they are the operator's facts: 443 on their machines runs their own site
-- and the 20000 range is taken by something else, while the chain-building UI fills the default back
-- in every time, so hardcoding them means editing by hand on every occasion.
--
-- They affect only the defaults for newly created things. Ports already in the model are untouched —
-- any change means an altered xray config, a process restart, and every connection on that machine
-- dropping. 8443 rather than 443 by default: something is usually on 443, a collision is two
-- processes fighting over one port, and the symptom only surfaces as a failed xray start. Using 443
-- is the operator's decision, one number away.
--
-- The probe endpoint is likewise the operator's fact and should not be compiled into the agent.
-- Cloudflare's trace rather than generate_204 by default: that 204 endpoint cannot return the exit
-- IP, and checking the exit is this feature's most valuable outcome. trace is plain HTTP returning
-- plain text and yields reachability, time to first byte, `ip=` (the exit IP), and `loc=` (the exit
-- country) in one request. The plaintext is not an oversight: what is measured is the chain itself,
-- and the endpoint site's TLS handshake should not mix into the number.
--
-- reality_flow follows the same "blank follows the global" rule as dest, server_names, and
-- fingerprint. It is global because flow decides the data plane's shape (Vision's inner layer wraps
-- no second TLS), two ingresses in one deployment using different shapes gains nothing in practice,
-- and it turns "why is this machine faster than that one" into an undiagnosable question. The
-- ingress column remains as an override, useful for rolling out machine by machine. NULL is the
-- "off" setting, aligned with the Rust side's `Option<String>` — that setting is a plain TLS proxy
-- exposing the TLS-in-TLS signature and should be chosen explicitly by the operator, hence a default
-- that is on (`model::DEFAULT_REALITY_FLOW`).
--
-- The allowlist holds one value, for reasons in Xray-core's source: a server-side account's flow can
-- only be vless.XRV ("xtls-rprx-vision") or the empty string, and anything else is
-- `unknown request flow`. The xtls-rprx-vision-udp443 often mistaken for a third value is purely
-- client-side — the outbound recognizes it, sets allowUDP443, and truncates the string to its first
-- 16 bytes (that is, XRV) before sending, so the server never sees that suffix. It is therefore a
-- subscription-side preference and does not belong in this column.
--
-- The three geodata columns are the auto-update parameters for geoip.dat / geosite.dat. The
-- `geosite:` and `geoip:` matches in rule tables rest entirely on those two files, and they go
-- stale — categories get renamed, domains enter and leave lists. The consequence of staleness is not
-- an error but rules quietly failing to match while traffic takes the fallback and nobody knows. So
-- this is not optional and there is no switch column: every machine running xray receives this
-- section.
--
-- Only the cron and the two URLs are stored, not the filenames: xray rewrites the `geosite:` prefix
-- into `ext:geosite.dat:`, so the landed filename is fixed and making it configurable would only let
-- someone configure a file that can never be read. The URLs must be configurable, because xray's
-- .dat download verifies neither signature nor checksum (`app/geodata/download.go` checks only the
-- HTTP status and a non-empty body) — trust follows wherever they point, and an operator has to be
-- able to point them at their own mirror. The two defaults are the copies Xray's own release
-- workflow pulls, the same source install.sh installs from the release archive, so enabling
-- auto-update does not change routing semantics.
CREATE TABLE IF NOT EXISTS control_state (
    id BOOLEAN DEFAULT true NOT NULL,
    overlay_cidr CIDR NOT NULL,
    current_revision BIGINT NOT NULL,
    -- The factory value for the client version floor. Blank ships no minClientVer and any version
    -- connects; with a floor, the server refuses clients below it (xray's minClientVer). 1.0.0 is a
    -- floor that blocks no real client, and its purpose is to leave this field on by default —
    -- tightening it is one number away rather than requiring somebody to first remember it was
    -- empty.
    reality_min_client_ver TEXT DEFAULT '1.0.0',
    reality_max_client_ver TEXT,
    reality_max_time_diff_ms BIGINT,
    -- Factory REALITY target. Ingresses that follow the global site inherit this pair; an
    -- operator can still replace it or choose a per-ingress custom target.
    reality_dest TEXT DEFAULT 'addons.mozilla.org:443',
    reality_server_names JSONB DEFAULT '["addons.mozilla.org"]'::jsonb NOT NULL,
    -- One current AnyTLS padding scheme. The store replaces this empty bootstrap marker with an
    -- installation-specific compact four-stage scheme immediately after migration; later
    -- regeneration goes through the ordinary settings revision and release path.
    anytls_padding_scheme JSONB DEFAULT '[]'::jsonb NOT NULL,
    -- The same value as materialize.rs's fallback on read, so as not to have two sources of truth
    -- where the database holds NULL and the read yields chrome.
    reality_fingerprint TEXT DEFAULT 'chrome',
    overlay_keepalive_secs INTEGER DEFAULT 25 NOT NULL,
    overlay_mtu INTEGER DEFAULT 1420 NOT NULL,
    -- Explicit exceptions to the otherwise full WireGuard mesh. Each JSON item is an
    -- undirected {"a":"node-a","b":"node-b"} pair, canonicalized by the store.
    overlay_disabled_links JSONB DEFAULT '[]'::jsonb NOT NULL,
    port_ingress_base INTEGER DEFAULT 8443 NOT NULL,
    port_anytls_base INTEGER DEFAULT 18443 NOT NULL,
    port_hop_base INTEGER DEFAULT 20000 NOT NULL,
    -- The same number as model.rs's HYSTERIA2_PORT_BASE, which is where a wire with no
    -- allocation of its own falls back to. Two sources for one factory value, but they are
    -- read on different paths (the console allocating, the model deserializing), and the
    -- alternative is a fresh database whose UDP base disagrees with its own wire default.
    port_hy2_base INTEGER DEFAULT 30000 NOT NULL,
    probe_endpoint_url TEXT DEFAULT 'http://cp.cloudflare.com/cdn-cgi/trace' NOT NULL,
    probe_timeout_secs INTEGER DEFAULT 10 NOT NULL,
    probe_interval_secs INTEGER DEFAULT 60 NOT NULL,
    reality_flow TEXT DEFAULT 'xtls-rprx-vision',
    geodata_cron TEXT DEFAULT 'CRON_TZ=Asia/Shanghai 30 6 * * *' NOT NULL,
    geodata_geoip_url TEXT DEFAULT 'https://raw.githubusercontent.com/Loyalsoldier/v2ray-rules-dat/release/geoip.dat' NOT NULL,
    geodata_geosite_url TEXT DEFAULT 'https://raw.githubusercontent.com/Loyalsoldier/v2ray-rules-dat/release/geosite.dat' NOT NULL,
    -- Where nodes reach this control plane, and which xray they install. Both sit here rather than
    -- alongside the settings above them, and the line is not filing: everything above compiles into
    -- artifacts, so writing one stamps a revision and travels through a release. These two compile
    -- into nothing — they decide what the enrolment command prints and what `/enroll/dist` serves,
    -- read at the moment somebody installs a machine. Stamping a revision for a domain typo would
    -- put it in the same ledger as a real configuration change, and carry it into `ModelSnapshot`,
    -- where recompiling an old revision would drag along a domain no artifact has ever held.
    -- `settings.rs` reads the columns above, `distribution.rs` these two, and only the first path
    -- creates revisions.
    --
    -- NULL means "not set here": the value falls through to the environment variable the process
    -- started with, and then to the built-in default. That is what lets a deployment already
    -- running on env vars keep behaving identically.
    agent_public_url TEXT,
    xray_version TEXT,
    -- Runtime log retention is operational policy, not compiled model state. Agent journal keeps
    -- the historical column name; Xray and Phantun have independent ceilings. Fleet defaults apply
    -- wherever the matching node column is NULL. Agent polls pick up changes without a revision.
    agent_log_max_mib INTEGER DEFAULT 100 NOT NULL,
    xray_log_max_mib INTEGER DEFAULT 100 NOT NULL,
    phantun_log_max_mib INTEGER DEFAULT 100 NOT NULL,
    -- Live NIC rates are kept only in control-plane memory, but whether the channel is available
    -- and its fleet-wide cadence must survive a restart. It is independent of both the persisted
    -- 30-second diagnostic windows and the cumulative usage ledger.
    realtime_enabled BOOLEAN DEFAULT TRUE NOT NULL,
    realtime_interval_secs INTEGER DEFAULT 1 NOT NULL,
    -- Console identity. It compiles into nothing and takes effect on the next browser fetch, so it
    -- shares control_state with distribution but not the revisioned model settings above.
    site_name TEXT DEFAULT 'Brocade' NOT NULL,
    -- A validated PNG/JPEG/WebP data URL. NULL keeps the built-in woven vector mark.
    site_icon_data_url TEXT,
    -- Startup creates the built-in line group exactly once. Keeping a durable marker separates
    -- a genuinely fresh installation from an operator who deliberately deleted every group.
    default_app_group_initialized BOOLEAN DEFAULT FALSE NOT NULL,
    -- Active TCP-connect and ICMP-echo observation. Operational and read by agents every round;
    -- it creates no model revision. The URI scheme selects tcp://host:port or icmp://host and both
    -- kinds may be configured at the same time.
    ping_probe_targets JSONB DEFAULT '[]'::jsonb NOT NULL,
    ping_probe_interval_secs INTEGER DEFAULT 60 NOT NULL,
    ping_probe_timeout_ms INTEGER DEFAULT 420 NOT NULL,
    -- Connection policy defaults. Merely the defaults: what reaches a machine is its own
    -- `nodes.conn_*` falling back to these, the same arrangement as overlay_mtu / nodes.mtu.
    --
