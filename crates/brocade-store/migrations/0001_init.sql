    CONSTRAINT ingresses_hy2_port_distinct CHECK ((hy2_port IS NULL) OR (transport_kind IS NULL) OR (hy2_port <> port)),
    CONSTRAINT ingresses_hy2_hop_pair CHECK ((hy2_hop_start IS NULL) = (hy2_hop_end IS NULL)),
    CONSTRAINT ingresses_hy2_hop_range CHECK (
