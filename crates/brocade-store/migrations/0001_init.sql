-- A relay hop's liveness.
--
-- Its own table apart from link_probes, because they answer two different questions at two different
-- granularities:
--   link_probes  how large a packet the path passes, per (node, peer), one for every pair under a
--                full mesh
--   link_health  whether this hop really forwards, per (node, chain, peer), only for hops in use
-- Merged into one table, half the rows would leave chain_id null, and "what does a null chain_id
-- mean" has no answer.
--
-- The test is the delta of the outbound counters: the artifacts' burstObservatory sends a probe
-- through every forwarding outbound every 10 seconds, so downlink keeps growing for as long as the
-- hop is alive. A zero delta means it is down. That separates idle from dead structurally and needs
-- no separate active probe.
--
-- Only the latest row is kept. History means little here: whether the link works now is what
-- matters, and for retrospection the agent's logs are more complete.
CREATE TABLE IF NOT EXISTS link_health (
    node_id TEXT NOT NULL,
    chain_id TEXT NOT NULL,
    peer_node_id TEXT NOT NULL,
    alive BOOLEAN NOT NULL,
    downlink_bytes BIGINT NOT NULL,
    window_secs BIGINT NOT NULL,
    checked_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ DEFAULT now() NOT NULL,
    CONSTRAINT link_health_bytes_match_alive CHECK (((alive AND (downlink_bytes > 0)) OR ((NOT alive) AND (downlink_bytes = 0)))),
    CONSTRAINT link_health_pkey PRIMARY KEY (node_id, chain_id, peer_node_id),
    CONSTRAINT link_health_node_id_fkey FOREIGN KEY (node_id) REFERENCES nodes(id) ON DELETE CASCADE,
    CONSTRAINT link_health_peer_node_id_fkey FOREIGN KEY (peer_node_id) REFERENCES nodes(id) ON DELETE CASCADE
);

-- Path-MTU probe results for backbone links.
--
-- Why this table exists: overlay_mtu is a number the operator picks in the settings (1420 by
-- default), and the symptom of picking wrongly is exceptionally hard to recognize — the tunnel is
-- up, the handshake is normal, small packets pass both ways, and only large ones are dropped,
-- presenting as pages that will not load while ping shows nothing wrong (measured once). Nobody can
-- know a cross-border link's effective MTU by intuition; it can only be measured.
--
-- Only the latest is stored, one row per (node, peer). History means little: a changed path MTU is
-- simply changed and old values feed no decision; for real retrospection the agent's logs are more
-- complete than this table.
--
-- The four statuses must stay apart (see LinkProbeStatus in protocol.rs):
--   ok          measured, with a path_mtu
--   unreachable not even an ordinary ping answers, and this row must not feed the global suggestion
--   blocked     the ping answers while every DF packet fails, most likely filtered ICMP — likewise
--               excluded
--   unsupported no ICMP socket can be opened on this machine (usually insufficient privilege), so
--               nothing can be measured
-- Recording unreachable or blocked as a very small number has the operator follow it and drop the
-- network-wide MTU to the floor, on links with nothing wrong with them. unsupported is a fact about
-- ourselves rather than about the link, and folded into blocked the whole fleet displays as "ICMP
-- filtered" while the operator hunts a filter that does not exist.
CREATE TABLE IF NOT EXISTS link_probes (
    node_id TEXT NOT NULL,
    peer_node_id TEXT NOT NULL,
    endpoint_host TEXT NOT NULL,
    status TEXT NOT NULL,
    path_mtu INTEGER,
    suggested_wg_mtu INTEGER,
    probed_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ DEFAULT now() NOT NULL,
    CONSTRAINT link_probes_mtu_matches_status CHECK ((((status = 'ok') AND (path_mtu IS NOT NULL) AND (suggested_wg_mtu IS NOT NULL)) OR ((status <> 'ok') AND (path_mtu IS NULL) AND (suggested_wg_mtu IS NULL)))),
    CONSTRAINT link_probes_mtu_range CHECK (((path_mtu IS NULL) OR ((path_mtu >= 576) AND (path_mtu <= 9000)))),
    CONSTRAINT link_probes_status CHECK ((status IN ('ok', 'unreachable', 'blocked', 'unsupported'))),
    CONSTRAINT link_probes_pkey PRIMARY KEY (node_id, peer_node_id),
    CONSTRAINT link_probes_node_id_fkey FOREIGN KEY (node_id) REFERENCES nodes(id) ON DELETE CASCADE,
    CONSTRAINT link_probes_peer_node_id_fkey FOREIGN KEY (peer_node_id) REFERENCES nodes(id) ON DELETE CASCADE
);

