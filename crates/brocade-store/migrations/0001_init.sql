-- The initial revision and the control plane's single-row state. These two are the minimum facts for
-- an empty database to run at all: current_revision has a foreign key into revisions, so the revision
-- must exist before control_state can.
-- The seed rows, both guarded rather than written as plain inserts. Re-applying this file must not
-- append a second bootstrap revision, and control_state is a one-row table whose primary key would
-- reject the duplicate outright — which would turn a harmless re-apply into a failed migration and
-- leave the control plane refusing to start.
INSERT INTO revisions (note)
SELECT 'initial schema revision'
WHERE NOT EXISTS (SELECT 1 FROM revisions WHERE note = 'initial schema revision');

INSERT INTO control_state (id, overlay_cidr, current_revision)
SELECT TRUE, '10.66.0.0/16'::cidr, id
FROM revisions
WHERE note = 'initial schema revision'
ON CONFLICT (id) DO NOTHING;

