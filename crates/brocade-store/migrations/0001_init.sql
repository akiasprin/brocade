CREATE OR REPLACE FUNCTION brocade_initialize_node_lifecycle() RETURNS TRIGGER
    LANGUAGE plpgsql
    AS $$
BEGIN
    INSERT INTO node_lifecycle_state (node_id, lifecycle_epoch, phase)
    VALUES (NEW.id, 0, 'active')
    ON CONFLICT (node_id) DO NOTHING;
    RETURN NEW;
END
$$;
