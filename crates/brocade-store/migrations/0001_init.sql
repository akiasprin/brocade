-- Raw samples of user traffic.
--
-- A usage row is a historical fact rather than a live model row, so the columns referencing the model
-- (this table's app_id / ingress_id, usage_chain_samples' app_id / chain_id) carry no foreign keys at
-- all: rolling back a revision `DELETE`s and rebuilds apps/chains/ingresses from the snapshot, and
-- with foreign keys on the samples, any machine that ever carried traffic would fail a legitimate
-- rollback. The samples carry the invariant keys auditing and billing need — tenant/user/ingress
-- labels for user traffic, app/chain/hop labels for link traffic, plus whatever revision and
-- deployment are available. Incoming counters are still validated against the current model, but a
-- historical row must not require that model object to remain present.
--
-- app_id is fixed at insert and does not follow the model afterwards. Derived at query time through
-- `JOIN ingresses i ON i.id = s.ingress_id`, an ingress moved to another view would take this
-- month's consumption with it the instant the model changed — a quota's numerator would jump. NULL is
-- allowed because unattributable cases exist (the ingress is already gone), and the query side falls
-- back to deriving it with `COALESCE(s.app_id, i.app_id)`.
CREATE TABLE usage_samples (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    sampled_at TIMESTAMPTZ DEFAULT now() NOT NULL,
    window_start TIMESTAMPTZ NOT NULL,
    window_end TIMESTAMPTZ NOT NULL,
    node_id TEXT NOT NULL,
    tenant_id TEXT NOT NULL,
    user_id TEXT NOT NULL,
    ingress_id TEXT NOT NULL,
    grant_label TEXT NOT NULL,
    uplink_bytes BIGINT NOT NULL,
    downlink_bytes BIGINT NOT NULL,
    has_gap BOOLEAN DEFAULT false NOT NULL,
    revision_id BIGINT,
    deployment_id BIGINT,
    app_id TEXT,
    generation_id BIGINT,
    CONSTRAINT usage_samples_check CHECK ((window_end > window_start)),
    CONSTRAINT usage_samples_downlink_bytes_check CHECK ((downlink_bytes >= 0)),
    CONSTRAINT usage_samples_uplink_bytes_check CHECK ((uplink_bytes >= 0)),
    CONSTRAINT usage_samples_node_id_grant_label_window_start_window_end_key UNIQUE (node_id, grant_label, window_start, window_end),
    CONSTRAINT usage_samples_pkey PRIMARY KEY (id),
    CONSTRAINT usage_samples_deployment_id_fkey FOREIGN KEY (deployment_id) REFERENCES deployments(id),
    CONSTRAINT usage_samples_node_id_fkey FOREIGN KEY (node_id) REFERENCES nodes(id) ON DELETE RESTRICT,
    CONSTRAINT usage_samples_revision_id_fkey FOREIGN KEY (revision_id) REFERENCES revisions(id),
    CONSTRAINT usage_samples_generation_id_fkey FOREIGN KEY (generation_id) REFERENCES usage_generations(id) ON DELETE RESTRICT,
    CONSTRAINT usage_samples_tenant_id_user_id_fkey FOREIGN KEY (tenant_id, user_id) REFERENCES users(tenant_id, id) ON DELETE RESTRICT
);


