    CONSTRAINT ingresses_hy2_obfs_password_check CHECK ((hy2_obfs_password IS NULL) OR (btrim(hy2_obfs_password) <> '')),
    CONSTRAINT ingresses_hy2_masquerade_kind_check CHECK (hy2_masquerade_kind IN ('not-found', 'proxy')),
    CONSTRAINT ingresses_hy2_masquerade_check CHECK (
        (hy2_masquerade_kind = 'not-found' AND hy2_masquerade_url IS NULL)
        OR (hy2_masquerade_kind = 'proxy' AND hy2_masquerade_url LIKE 'https://%')
    ),
    -- "No projection" can only be expressed by both columns being NULL. An empty string and a
