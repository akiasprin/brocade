-- One node's certificate, and everything about the attempt to get it.
--
-- # Why the private key is here at all
--
-- An earlier design had each node generate its own key and run ACME itself, so that no private key
-- ever reached the control plane. It was dropped after pricing it: the control plane holds the DNS
-- credential, so whoever takes the control plane can already issue a fresh certificate for any
-- name in the domain and impersonate any node. Keeping the key on the node defends only against a
-- database stolen without that credential, and costs an ACME client, an account, and a retry
-- policy on every machine, plus an API for nodes to ask the control plane to write DNS.
--
-- What that trade does oblige: `key_pem_sealed` is sealed at rest, the console API never returns
-- it, and it must never reach a log or an error message. It is not the same class as the UUIDs
-- and short ids stored elsewhere — those leak one account, this leaks a machine's identity.
--
-- # Why status carries an error and a count
--
-- The failure that matters is not a single attempt failing; it is a certificate quietly reaching
-- its expiry while attempts keep failing. `status`, `attempts` and `last_error` exist so the
-- console can say which, and say it before the expiry rather than after — a node whose certificate
-- expired does not degrade, it stops answering.
-- A certificate group: one shared SNI identity that any number of machines may present.
--
-- The label is what TLS sees and it stays random; `name` is what a person sees. They are separate
-- because every issued certificate is published to Certificate Transparency, so a readable label
-- would put the fleet's topology in a public log — while an unreadable name would make the console
-- unusable. Random does not hide that the group exists, it only stops the name from saying what it
-- is for.
--
-- Grouping is the whole point of this table: machines sharing a group present the same certificate,
-- which costs one Let's Encrypt quota slot per group rather than per machine (50 certificates per
-- registered domain per 7 days, 5 per identical name set). The price is that an observer seeing the
-- same certificate on several addresses learns they belong together, so a group is exactly "the set
-- of machines willing to be seen together".
CREATE TABLE cert_labels (
    id TEXT NOT NULL,
    domain_id TEXT NOT NULL,
    label TEXT NOT NULL,
    -- Shown wherever a group has to be picked or reported. Required, because the alternative is an
    -- operator choosing between two rows of hex.
    name TEXT NOT NULL,
    note TEXT,
    -- draining: still serving the machines it has, but takes no new ones. retired: nothing points
    -- at it any more.
    status TEXT DEFAULT 'active' NOT NULL,
    -- Self-signed groups use one exact synthetic SNI. Public-CA groups leave this NULL and use
    -- their wildcard/bare-name pair.
    certificate_name TEXT,
    is_default BOOLEAN DEFAULT FALSE NOT NULL,
    created_at TIMESTAMPTZ DEFAULT now() NOT NULL,
    CONSTRAINT cert_labels_pkey PRIMARY KEY (id),
    CONSTRAINT cert_labels_label_key UNIQUE (domain_id, label),
    -- Names are referenced by people, so two groups called 香港 would leave them guessing. The
    -- fixed name of the default group takes part in this, which is what stops a second one.
    CONSTRAINT cert_labels_name_key UNIQUE (domain_id, name),
    CONSTRAINT cert_labels_name_present CHECK ((length(btrim(name)) > 0)),
    CONSTRAINT cert_labels_label_shape CHECK ((label ~ '^[0-9a-f]{8,32}$')),
    CONSTRAINT cert_labels_status_known CHECK ((status IN ('active', 'draining', 'retired'))),
    CONSTRAINT cert_labels_certificate_name_shape CHECK (
        certificate_name IS NULL OR
        certificate_name ~ '^[a-z0-9]([a-z0-9-]*[a-z0-9])?(\.[a-z0-9]([a-z0-9-]*[a-z0-9])?)+$'
    ),
    CONSTRAINT cert_labels_domain_id_fkey FOREIGN KEY (domain_id) REFERENCES cert_domains(id) ON DELETE RESTRICT
);

CREATE UNIQUE INDEX cert_labels_certificate_name_key
    ON cert_labels (certificate_name)
    WHERE certificate_name IS NOT NULL;
CREATE UNIQUE INDEX cert_labels_one_default
    ON cert_labels (is_default)
    WHERE is_default;

-- The certificates inside a group. Several may exist at once for the same set of names: one is
-- serving, the rest are spares an operator asked for in advance, or the one that just replaced.
--
-- Rolling within a group is why this is a table of its own rather than columns on cert_labels.
-- Swapping which row is `serving` changes the bytes the agents fetch while the names — and
-- therefore every `sni` already handed out in a subscription — stay exactly as they were.
CREATE TABLE certificates (
    id TEXT NOT NULL,
    label_id TEXT NOT NULL,
    cert_pem TEXT,
    key_pem_sealed TEXT,
    issued_at TIMESTAMPTZ,
    expires_at TIMESTAMPTZ,
    -- pending: asked for, not yet in hand. ready: in hand, held as a spare. serving: the one the
    -- group's machines are told to present. superseded: was serving, has been replaced. failed:
    -- issuance failed and this row records why.
    status TEXT DEFAULT 'pending' NOT NULL,
    -- Why this row exists, which decides what happens the moment it is issued.
    --
    -- renewal: the scan asked for it because the serving one is running out. It takes over on
    -- arrival — leaving it for somebody to activate is how a certificate expires with its
    -- replacement sitting in the database.
    --
    -- spare: an operator asked for it in advance. It waits, because the point of asking early is
    -- to choose the moment. A spare must therefore never be mistaken for a renewal, which is the
    -- whole reason this column exists rather than a heuristic on dates.
    origin TEXT DEFAULT 'renewal' NOT NULL,
    attempts INTEGER DEFAULT 0 NOT NULL,
    last_error TEXT,
    last_attempt_at TIMESTAMPTZ,
    -- The issuing CA's common name, copied out of the certificate rather than derived from the
    -- configured ACME directory. Those two can disagree, and only one of them is a fact: a fleet
    -- left pointing at a staging directory shows every group ready while nothing trusts a single
    -- certificate, and this column is where that says itself out loud.
    issuer TEXT,
    -- SHA-256 of the leaf certificate's DER bytes. This is deliberately distinct from the digest
    -- of cert_pem used to reconcile the file on a node: Xray's pinnedPeerCertSha256 verifies the
    -- X.509 certificate, not the PEM file containing it and the rest of its chain.
    peer_sha256 TEXT,
    -- Which ACME directory issued this. Recorded so that changing the domain's directory makes
    -- everything under it due again: an operator moving from staging to production has said the
    -- certificates they hold are not the ones they want, and nothing else here can tell.
    acme_directory TEXT,
    -- Self-signed generations have independent SNI identities. Public-CA rows keep this NULL and
