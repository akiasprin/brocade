CREATE TABLE vpngate_catalog_state (
    id BOOLEAN NOT NULL,
    enabled BOOLEAN DEFAULT true NOT NULL,
    interval_secs INTEGER DEFAULT 900 NOT NULL,
    -- Successful connectivity checks stay out of the catalogue probe queue for this long. Full
    -- single-stream performance measurements have their own slower schedule. Ownership of the
    -- retained directory rotates independently so one machine does not keep the same shard.
    probe_success_cooldown_secs INTEGER DEFAULT 1800 NOT NULL,
    probe_performance_cooldown_secs INTEGER DEFAULT 21600 NOT NULL,
    probe_shard_rotation_secs INTEGER DEFAULT 21600 NOT NULL,
    source_url TEXT DEFAULT 'https://www.vpngate.net/api/iphone/' NOT NULL,
    -- Risk scores are provider-local inputs. The policy first evaluates every source against its
    -- own threshold and only then combines pass/reject decisions; it never takes MAX across scores.
    admission_policy JSONB DEFAULT '{"minimum_successful_sources":1,"country_policy":"any_match","risk_decision_policy":"all_available_pass","provider_rules":[{"provider":"proxycheck","maximum_score":80},{"provider":"ffraud","maximum_score":80},{"provider":"iplogs","maximum_score":80}]}'::jsonb NOT NULL,
    -- Intelligence collection is operational policy, separate from admission. By default an exact
    -- exit IP is queried once, remains eligible for refresh only while it has dialled successfully
    -- within 72 hours, and retained evidence does not expire out of serving eligibility.
    intelligence_policy JSONB DEFAULT '{"refresh_mode":"on_change","refresh_interval_hours":168,"active_window_hours":72,"stale_policy":"retain","stale_after_hours":168}'::jsonb NOT NULL,
    -- Encrypted ProxyCheck key pool, including its round-robin cursor. Only the one key assigned to
    -- an authenticated worker's current lease leaves the Console; admin reads expose neither.
    proxycheck_api_key_sealed TEXT,
    next_sync_at TIMESTAMPTZ DEFAULT now() NOT NULL,
    lease_owner TEXT,
    lease_generation BIGINT DEFAULT 0 NOT NULL,
    lease_until TIMESTAMPTZ,
    active_run_id BIGINT,
    last_success_run_id BIGINT,
    -- Exact retained-row accounting keeps the overview endpoint O(1). Counting the append-only
    -- observation table on every page load became a full scan once distributed collection was
    -- enabled on the whole fleet.
    retained_observation_count BIGINT DEFAULT 0 NOT NULL,
    last_error_code TEXT,
    last_error_detail TEXT,
    updated_at TIMESTAMPTZ DEFAULT now() NOT NULL,
    CONSTRAINT vpngate_catalog_state_pkey PRIMARY KEY (id),
    CONSTRAINT vpngate_catalog_state_id_check CHECK (id),
    CONSTRAINT vpngate_catalog_state_interval_range CHECK (interval_secs BETWEEN 60 AND 86400),
    CONSTRAINT vpngate_catalog_state_probe_success_cooldown_range CHECK (
        probe_success_cooldown_secs BETWEEN 60 AND 86400
        AND probe_success_cooldown_secs % 60 = 0
    ),
    CONSTRAINT vpngate_catalog_state_probe_performance_cooldown_range CHECK (
        probe_performance_cooldown_secs BETWEEN 3600 AND 604800
        AND probe_performance_cooldown_secs % 3600 = 0
    ),
    CONSTRAINT vpngate_catalog_state_probe_shard_rotation_range CHECK (
        probe_shard_rotation_secs BETWEEN 3600 AND 604800
        AND probe_shard_rotation_secs % 3600 = 0
    ),
    CONSTRAINT vpngate_catalog_state_source_https CHECK (source_url ~ '^https://'),
    CONSTRAINT vpngate_catalog_state_admission_policy_object CHECK (jsonb_typeof(admission_policy) = 'object'),
    CONSTRAINT vpngate_catalog_state_intelligence_policy_object CHECK (jsonb_typeof(intelligence_policy) = 'object'),
    CONSTRAINT vpngate_catalog_state_observation_count_nonnegative CHECK (retained_observation_count >= 0),
    CONSTRAINT vpngate_catalog_state_lease_coherent CHECK (
        (lease_owner IS NULL AND lease_until IS NULL AND active_run_id IS NULL)
        OR (lease_owner IS NOT NULL AND lease_until IS NOT NULL AND active_run_id IS NOT NULL)
    ),
    CONSTRAINT vpngate_catalog_state_active_run_fkey FOREIGN KEY (active_run_id) REFERENCES vpngate_sync_runs(id),
    CONSTRAINT vpngate_catalog_state_last_success_fkey FOREIGN KEY (last_success_run_id) REFERENCES vpngate_sync_runs(id)
);

