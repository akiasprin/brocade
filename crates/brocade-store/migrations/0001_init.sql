-- A release's observations: what state the four node artifacts are in on the machine.
--
-- 'unknown' means never observed and triggers action; 'unmanaged' means the agent stated explicitly
-- that this is not its to manage, which only the agent can say (the serde default in protocol.rs).
-- The control plane saying it on the agent's behalf deadlocks — `artifact_needs_action` returns false
-- for `Present` against `Unmanaged`, so that machine never enters a release's targets; out of the
-- targets it receives no desired state, without which it does not converge, and it therefore never
-- gets the chance to report a real state and change this field. That is why phantun_state's column
-- defaults to 'unknown'.
