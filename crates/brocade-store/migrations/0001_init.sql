CREATE OR REPLACE FUNCTION brocade_is_grouped_model_id(kind TEXT, value TEXT) RETURNS BOOLEAN
    LANGUAGE sql IMMUTABLE STRICT
    AS $_$
    SELECT CASE kind
        WHEN 'app' THEN value ~ '^app-[0-9a-f]{4}$'
        WHEN 'chain' THEN value ~ '^chn-[0-9a-f]{4}-[0-9a-f]{4}$'
        WHEN 'ingress' THEN value ~ '^ing-[0-9a-f]{4}$'
        ELSE FALSE
    END
$_$;

CREATE OR REPLACE FUNCTION brocade_random_model_id_token() RETURNS TEXT
    LANGUAGE sql VOLATILE
    AS $_$
    SELECT substr(md5(random()::TEXT || clock_timestamp()::TEXT), 1, 4)
$_$;

-- Convert every active and historical association together. Apps receive an independent random
-- token. An ingress owns the first four hexadecimal characters and its chain carries the same token
-- plus an independent suffix. The temporary source tables include deleted objects still present in
-- rollback snapshots, so no old identifier can return through a later rollback.
CREATE OR REPLACE FUNCTION brocade_migrate_grouped_model_ids() RETURNS INTEGER
    LANGUAGE plpgsql
    AS $_$
DECLARE
    source RECORD;
    stored RECORD;
    app_doc JSONB;
    chain_doc JSONB;
    ingress_doc JSONB;
    front_doc JSONB;
    step_doc JSONB;
    grant_doc JSONB;
    apps_doc JSONB;
    chains_doc JSONB;
    ingresses_doc JSONB;
    fronts_doc JSONB;
    steps_doc JSONB;
    grants_doc JSONB;
    old_app TEXT;
    new_app TEXT;
    old_chain TEXT;
    new_chain TEXT;
    old_ingress TEXT;
    new_ingress TEXT;
    candidate_token TEXT;
    candidate TEXT;
    attempts INTEGER;
    previous_revision BIGINT;
    migration_revision BIGINT;
    previous_snapshot JSONB;
    changed INTEGER;
BEGIN
    CREATE TEMP TABLE _brocade_app_id_sources (
        old_id TEXT PRIMARY KEY
    ) ON COMMIT DROP;
    CREATE TEMP TABLE _brocade_chain_id_sources (
        old_id TEXT PRIMARY KEY
    ) ON COMMIT DROP;
    CREATE TEMP TABLE _brocade_ingress_id_sources (
        old_id TEXT PRIMARY KEY
    ) ON COMMIT DROP;
    CREATE TEMP TABLE _brocade_chain_ingress_sources (
        old_chain_id TEXT NOT NULL,
        old_ingress_id TEXT NOT NULL,
        observed_revision BIGINT NOT NULL,
        PRIMARY KEY (old_chain_id, old_ingress_id)
    ) ON COMMIT DROP;
    CREATE TEMP TABLE _brocade_chain_id_map (
        old_id TEXT PRIMARY KEY,
        new_id TEXT NOT NULL UNIQUE
    ) ON COMMIT DROP;
    CREATE TEMP TABLE _brocade_app_id_map (
        old_id TEXT PRIMARY KEY,
        new_id TEXT NOT NULL UNIQUE
    ) ON COMMIT DROP;
    CREATE TEMP TABLE _brocade_ingress_id_map (
        old_id TEXT PRIMARY KEY,
        new_id TEXT NOT NULL UNIQUE,
        token TEXT NOT NULL UNIQUE
    ) ON COMMIT DROP;
    CREATE TEMP TABLE _brocade_hop_id_map (
        old_id TEXT PRIMARY KEY,
        new_id TEXT NOT NULL UNIQUE
    ) ON COMMIT DROP;

    INSERT INTO _brocade_app_id_sources SELECT id FROM apps;
    INSERT INTO _brocade_chain_id_sources SELECT id FROM chains;
    INSERT INTO _brocade_ingress_id_sources SELECT id FROM ingresses;
    INSERT INTO _brocade_chain_ingress_sources
    SELECT chain_id, id, 9223372036854775807 FROM ingresses;

    INSERT INTO _brocade_app_id_sources (old_id)
    SELECT DISTINCT app_value->>'id'
      FROM model_snapshots AS snapshot_row
      CROSS JOIN LATERAL jsonb_array_elements(COALESCE(snapshot_row.snapshot->'apps', '[]'::jsonb)) AS app_item(app_value)
     WHERE app_value->>'id' IS NOT NULL
    ON CONFLICT (old_id) DO NOTHING;

    INSERT INTO _brocade_app_id_sources (old_id)
    SELECT app_id FROM quota_suspensions
    UNION
    SELECT app_id FROM usage_chain_samples
    UNION
    SELECT app_id FROM usage_samples WHERE app_id IS NOT NULL
    UNION
    SELECT app_id FROM user_app_quotas
    UNION
    SELECT split_part(chain_id, '/', 1) FROM link_health WHERE strpos(chain_id, '/') > 0
    UNION
    SELECT split_part(chain_id, '/', 1) FROM node_hop_link_samples WHERE strpos(chain_id, '/') > 0
    ON CONFLICT (old_id) DO NOTHING;

    INSERT INTO _brocade_chain_id_sources (old_id)
    SELECT DISTINCT chain_value->>'id'
      FROM model_snapshots AS snapshot_row
      CROSS JOIN LATERAL jsonb_array_elements(COALESCE(snapshot_row.snapshot->'apps', '[]'::jsonb)) AS app_item(app_value)
      CROSS JOIN LATERAL jsonb_array_elements(COALESCE(app_value->'chains', '[]'::jsonb)) AS chain_item(chain_value)
     WHERE chain_value->>'id' IS NOT NULL
    ON CONFLICT (old_id) DO NOTHING;

    INSERT INTO _brocade_ingress_id_sources (old_id)
    SELECT DISTINCT ingress_value->>'id'
      FROM model_snapshots AS snapshot_row
      CROSS JOIN LATERAL jsonb_array_elements(COALESCE(snapshot_row.snapshot->'apps', '[]'::jsonb)) AS app_item(app_value)
      CROSS JOIN LATERAL jsonb_array_elements(COALESCE(app_value->'ingresses', '[]'::jsonb)) AS ingress_item(ingress_value)
     WHERE ingress_value->>'id' IS NOT NULL
    ON CONFLICT (old_id) DO NOTHING;

    INSERT INTO _brocade_chain_ingress_sources (old_chain_id, old_ingress_id, observed_revision)
    SELECT ingress_value->>'chain', ingress_value->>'id', max(snapshot_row.revision_id)
      FROM model_snapshots AS snapshot_row
      CROSS JOIN LATERAL jsonb_array_elements(COALESCE(snapshot_row.snapshot->'apps', '[]'::jsonb)) AS app_item(app_value)
      CROSS JOIN LATERAL jsonb_array_elements(COALESCE(app_value->'ingresses', '[]'::jsonb)) AS ingress_item(ingress_value)
     WHERE ingress_value->>'id' IS NOT NULL
       AND ingress_value->>'chain' IS NOT NULL
     GROUP BY ingress_value->>'chain', ingress_value->>'id'
    ON CONFLICT (old_chain_id, old_ingress_id) DO UPDATE
        SET observed_revision = GREATEST(
            _brocade_chain_ingress_sources.observed_revision,
            EXCLUDED.observed_revision
        );

    FOR source IN
        SELECT old_id
          FROM _brocade_app_id_sources
         WHERE NOT brocade_is_grouped_model_id('app', old_id)
         ORDER BY old_id
    LOOP
        attempts := 0;
        LOOP
            attempts := attempts + 1;
            IF attempts > 65536 THEN
                RAISE EXCEPTION 'exhausted four-character app id space';
            END IF;
            candidate := 'app-' || brocade_random_model_id_token();
            EXIT WHEN NOT EXISTS (
                              SELECT 1 FROM _brocade_app_id_sources WHERE old_id = candidate
                          )
                          AND NOT EXISTS (
                              SELECT 1 FROM _brocade_app_id_map WHERE new_id = candidate
                          );
        END LOOP;
        INSERT INTO _brocade_app_id_map VALUES (source.old_id, candidate);
    END LOOP;

    -- Allocate ingress tokens first. If its chain already has the new format, retain that chain's
    -- token; this makes an interrupted or partially repaired conversion converge to the same pair.
    FOR source IN
        SELECT ingress.old_id,
               (
                   SELECT substr(relation.old_chain_id, 5, 4)
                     FROM _brocade_chain_ingress_sources AS relation
                    WHERE relation.old_ingress_id = ingress.old_id
                      AND brocade_is_grouped_model_id('chain', relation.old_chain_id)
                    ORDER BY relation.observed_revision DESC, relation.old_chain_id
                    LIMIT 1
               ) AS preferred_token
          FROM _brocade_ingress_id_sources AS ingress
         WHERE NOT brocade_is_grouped_model_id('ingress', ingress.old_id)
         ORDER BY ingress.old_id
    LOOP
        candidate_token := source.preferred_token;
        attempts := 0;
        LOOP
            attempts := attempts + 1;
            IF attempts > 65536 THEN
                RAISE EXCEPTION 'exhausted four-character ingress id space';
            END IF;
            IF candidate_token IS NULL THEN
                candidate_token := brocade_random_model_id_token();
            END IF;
            candidate := 'ing-' || candidate_token;
            EXIT WHEN NOT EXISTS (
                          SELECT 1 FROM _brocade_ingress_id_sources WHERE old_id = candidate
                      )
                      AND NOT EXISTS (SELECT 1 FROM _brocade_ingress_id_map WHERE new_id = candidate)
                      AND (
                          source.preferred_token IS NOT NULL
                          OR NOT EXISTS (
                              SELECT 1
                                FROM _brocade_chain_id_sources
                               WHERE brocade_is_grouped_model_id('chain', old_id)
                                 AND substr(old_id, 5, 4) = candidate_token
                          )
                      );
            IF source.preferred_token IS NOT NULL THEN
                RAISE EXCEPTION 'chain token % is already owned by another ingress', candidate_token;
            END IF;
            candidate_token := NULL;
        END LOOP;
        INSERT INTO _brocade_ingress_id_map VALUES (source.old_id, candidate, candidate_token);
    END LOOP;

    -- A chain takes the token of its first ingress. Orphan chains receive an unused token so a
    -- later repair can create the matching ingress without renaming the chain again.
    FOR source IN
        SELECT chain.old_id,
               (
                   SELECT COALESCE(mapped.token, substr(ingress.old_id, 5, 4))
                     FROM _brocade_chain_ingress_sources AS relation
                     JOIN _brocade_ingress_id_sources AS ingress
                       ON ingress.old_id = relation.old_ingress_id
                     LEFT JOIN _brocade_ingress_id_map AS mapped ON mapped.old_id = ingress.old_id
                    WHERE relation.old_chain_id = chain.old_id
                      AND (mapped.token IS NOT NULL OR brocade_is_grouped_model_id('ingress', ingress.old_id))
                    ORDER BY relation.observed_revision DESC, ingress.old_id
                    LIMIT 1
               ) AS ingress_token
          FROM _brocade_chain_id_sources AS chain
         WHERE NOT brocade_is_grouped_model_id('chain', chain.old_id)
         ORDER BY chain.old_id
    LOOP
        candidate_token := source.ingress_token;
        IF candidate_token IS NULL THEN
            attempts := 0;
            LOOP
                attempts := attempts + 1;
                IF attempts > 65536 THEN
                    RAISE EXCEPTION 'exhausted four-character ingress-group token space';
                END IF;
                candidate_token := brocade_random_model_id_token();
                EXIT WHEN NOT EXISTS (
                                  SELECT 1
                                    FROM _brocade_ingress_id_sources
                                   WHERE brocade_is_grouped_model_id('ingress', old_id)
                                     AND substr(old_id, 5, 4) = candidate_token
                              )
                              AND NOT EXISTS (
                                  SELECT 1 FROM _brocade_ingress_id_map WHERE token = candidate_token
                              )
                              AND NOT EXISTS (
                                  SELECT 1
                                    FROM _brocade_chain_id_sources
                                   WHERE brocade_is_grouped_model_id('chain', old_id)
                                     AND substr(old_id, 5, 4) = candidate_token
                              )
                              AND NOT EXISTS (
                                  SELECT 1
                                    FROM _brocade_chain_id_map
                                   WHERE substr(new_id, 5, 4) = candidate_token
                              );
            END LOOP;
        END IF;
        attempts := 0;
        LOOP
            attempts := attempts + 1;
            IF attempts > 65536 THEN
                RAISE EXCEPTION 'exhausted four-character chain id space for ingress token %', candidate_token;
            END IF;
            candidate := 'chn-' || candidate_token || '-' || brocade_random_model_id_token();
            EXIT WHEN NOT EXISTS (
                              SELECT 1 FROM _brocade_chain_id_sources WHERE old_id = candidate
                          )
                          AND NOT EXISTS (
                              SELECT 1 FROM _brocade_chain_id_map WHERE new_id = candidate
                          );
        END LOOP;
        INSERT INTO _brocade_chain_id_map VALUES (source.old_id, candidate);
    END LOOP;

    INSERT INTO _brocade_hop_id_map (old_id, new_id)
    SELECT chain.app_id || '/' || chain.id,
           COALESCE(app_map.new_id, chain.app_id) || '/' || COALESCE(chain_map.new_id, chain.id)
      FROM chains AS chain
      LEFT JOIN _brocade_chain_id_map AS chain_map ON chain_map.old_id = chain.id
      LEFT JOIN _brocade_app_id_map AS app_map ON app_map.old_id = chain.app_id
     WHERE chain_map.new_id IS NOT NULL OR app_map.new_id IS NOT NULL;
    INSERT INTO _brocade_hop_id_map (old_id, new_id)
    SELECT historical.old_id,
           app_map.new_id || substr(historical.old_id, length(app_map.old_id) + 1)
      FROM (
          SELECT chain_id AS old_id FROM link_health WHERE strpos(chain_id, '/') > 0
          UNION
          SELECT chain_id AS old_id FROM node_hop_link_samples WHERE strpos(chain_id, '/') > 0
      ) AS historical
      JOIN _brocade_app_id_map AS app_map
        ON app_map.old_id = split_part(historical.old_id, '/', 1)
    ON CONFLICT (old_id) DO NOTHING;

    SELECT (SELECT count(*) FROM _brocade_app_id_map)
         + (SELECT count(*) FROM _brocade_chain_id_map)
         + (SELECT count(*) FROM _brocade_ingress_id_map)
      INTO changed;
    IF changed = 0 THEN
        RETURN 0;
    END IF;

    -- Historical snapshots are rollback sources, not display caches. Rewrite their structured
    -- references before changing the live tables so either side of a rollback uses one id family.
    FOR stored IN SELECT revision_id, snapshot FROM model_snapshots ORDER BY revision_id LOOP
        apps_doc := '[]'::jsonb;
        FOR app_doc IN SELECT value FROM jsonb_array_elements(COALESCE(stored.snapshot->'apps', '[]'::jsonb)) LOOP
            old_app := app_doc->>'id';
            SELECT new_id INTO new_app FROM _brocade_app_id_map WHERE old_id = old_app;
            new_app := COALESCE(new_app, old_app);
            chains_doc := '[]'::jsonb;
            FOR chain_doc IN SELECT value FROM jsonb_array_elements(COALESCE(app_doc->'chains', '[]'::jsonb)) LOOP
                old_chain := chain_doc->>'id';
                SELECT new_id INTO new_chain FROM _brocade_chain_id_map WHERE old_id = old_chain;
                new_chain := COALESCE(new_chain, old_chain);
                chain_doc := jsonb_set(chain_doc, '{id}', to_jsonb(new_chain), false);
                IF chain_doc->>'name' = old_chain THEN
                    chain_doc := jsonb_set(chain_doc, '{name}', to_jsonb(new_chain), false);
                END IF;
                chains_doc := chains_doc || jsonb_build_array(chain_doc);
            END LOOP;
            app_doc := jsonb_set(app_doc, '{chains}', chains_doc, false);

            ingresses_doc := '[]'::jsonb;
            FOR ingress_doc IN SELECT value FROM jsonb_array_elements(COALESCE(app_doc->'ingresses', '[]'::jsonb)) LOOP
                old_ingress := ingress_doc->>'id';
                SELECT new_id INTO new_ingress FROM _brocade_ingress_id_map WHERE old_id = old_ingress;
                new_ingress := COALESCE(new_ingress, old_ingress);
                old_chain := ingress_doc->>'chain';
                SELECT new_id INTO new_chain FROM _brocade_chain_id_map WHERE old_id = old_chain;
                new_chain := COALESCE(new_chain, old_chain);
                ingress_doc := jsonb_set(ingress_doc, '{id}', to_jsonb(new_ingress), false);
                ingress_doc := jsonb_set(ingress_doc, '{chain}', to_jsonb(new_chain), false);
                ingresses_doc := ingresses_doc || jsonb_build_array(ingress_doc);
            END LOOP;
            app_doc := jsonb_set(app_doc, '{ingresses}', ingresses_doc, false);

            fronts_doc := '[]'::jsonb;
            FOR front_doc IN SELECT value FROM jsonb_array_elements(COALESCE(app_doc->'fronts', '[]'::jsonb)) LOOP
                SELECT COALESCE(jsonb_agg(to_jsonb(COALESCE(mapped.new_id, item.value)) ORDER BY item.ordinality), '[]'::jsonb)
                  INTO ingresses_doc
                  FROM jsonb_array_elements_text(COALESCE(front_doc->'via', '[]'::jsonb)) WITH ORDINALITY AS item(value, ordinality)
                  LEFT JOIN _brocade_ingress_id_map AS mapped ON mapped.old_id = item.value;
                front_doc := jsonb_set(front_doc, '{via}', ingresses_doc, false);
                fronts_doc := fronts_doc || jsonb_build_array(front_doc);
            END LOOP;
            app_doc := jsonb_set(app_doc, '{fronts}', fronts_doc, false);

            steps_doc := '[]'::jsonb;
            FOR step_doc IN SELECT value FROM jsonb_array_elements(COALESCE(app_doc->'steps', '[]'::jsonb)) LOOP
                old_chain := step_doc->>'chain';
                SELECT new_id INTO new_chain FROM _brocade_chain_id_map WHERE old_id = old_chain;
                new_chain := COALESCE(new_chain, old_chain);
                step_doc := jsonb_set(step_doc, '{chain}', to_jsonb(new_chain), false);
                IF step_doc#>>'{accept,label}' = old_chain || '@' || (step_doc->>'node') THEN
                    step_doc := jsonb_set(step_doc, '{accept,label}', to_jsonb(new_chain || '@' || (step_doc->>'node')), false);
                END IF;
                steps_doc := steps_doc || jsonb_build_array(step_doc);
            END LOOP;
            app_doc := jsonb_set(app_doc, '{steps}', steps_doc, false);

            grants_doc := '[]'::jsonb;
            FOR grant_doc IN SELECT value FROM jsonb_array_elements(COALESCE(app_doc->'grants', '[]'::jsonb)) LOOP
                old_ingress := grant_doc->>'ingress';
                SELECT new_id INTO new_ingress FROM _brocade_ingress_id_map WHERE old_id = old_ingress;
                new_ingress := COALESCE(new_ingress, old_ingress);
                grant_doc := jsonb_set(grant_doc, '{ingress}', to_jsonb(new_ingress), false);
                grants_doc := grants_doc || jsonb_build_array(grant_doc);
            END LOOP;
            app_doc := jsonb_set(app_doc, '{grants}', grants_doc, false);
            app_doc := jsonb_set(app_doc, '{id}', to_jsonb(new_app), false);
            IF app_doc->>'label' = old_app THEN
                app_doc := jsonb_set(app_doc, '{label}', to_jsonb(new_app), false);
            END IF;
            apps_doc := apps_doc || jsonb_build_array(app_doc);
        END LOOP;
        UPDATE model_snapshots
           SET snapshot = jsonb_set(stored.snapshot, '{apps}', apps_doc, false)
         WHERE revision_id = stored.revision_id;
    END LOOP;

    UPDATE apps AS live SET id = mapped.new_id,
        label = CASE WHEN live.label = mapped.old_id THEN mapped.new_id ELSE live.label END
      FROM _brocade_app_id_map AS mapped WHERE live.id = mapped.old_id;
    UPDATE chains AS live SET id = mapped.new_id,
        name = CASE WHEN live.name = mapped.old_id THEN mapped.new_id ELSE live.name END
      FROM _brocade_chain_id_map AS mapped WHERE live.id = mapped.old_id;
    UPDATE ingresses AS live SET id = mapped.new_id
      FROM _brocade_ingress_id_map AS mapped WHERE live.id = mapped.old_id;

    UPDATE steps AS live SET accept_label = mapped.new_id || substr(live.accept_label, length(mapped.old_id) + 1)
      FROM _brocade_chain_id_map AS mapped
     WHERE live.chain_id = mapped.new_id AND live.accept_label LIKE mapped.old_id || '@%';
    UPDATE link_health AS live SET chain_id = mapped.new_id
      FROM _brocade_hop_id_map AS mapped WHERE live.chain_id = mapped.old_id;
    UPDATE link_health AS live SET chain_id = mapped.new_id
      FROM _brocade_chain_id_map AS mapped WHERE live.chain_id = mapped.old_id;
    UPDATE node_hop_link_samples AS live SET chain_id = mapped.new_id
      FROM _brocade_hop_id_map AS mapped WHERE live.chain_id = mapped.old_id;
    UPDATE node_hop_link_samples AS live SET chain_id = mapped.new_id
