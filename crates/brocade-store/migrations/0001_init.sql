-- Grants the system revoked because a quota was spent.
--
-- Without this table, revoking would be possible and restoring would not. A month resetting, a quota
-- being raised, and a quota being deleted all have the system add grants back; but whether a grant
-- was revoked by the system or by a person must stay distinguishable — a grant a person revoked by
-- hand is not the system's to add back at the start of a month.
--
-- Recorded at the ingress level: quotas are set per (user, view) while grants are stored per (user,
-- ingress), so a view with several ingresses means revoking several rows. Restoring requires knowing
-- which rows were revoked and cannot infer them from which ingresses the view has now — ingresses
-- added and removed in between leave the inferred set disagreeing with what was revoked.
--
-- The marker cannot go on the grants table: rolling back a revision does a `DELETE FROM grants` and
-- rebuilds wholesale (clear_app_model_tx in deployment.rs), taking the markers with it. So like
-- user_app_quotas it is operational data outside the model.
--
-- app_id and ingress_id likewise have no foreign keys, for the same reason: a rollback rebuilds apps
-- wholesale, CASCADE would delete these rows along with them, and RESTRICT would block the rollback.
-- The tenant/user pair can have them — restore_users_tx goes through UPSERT and those rows do not
-- vanish; and when a user is deleted these suspension records should go too.
CREATE TABLE IF NOT EXISTS quota_suspensions (
    tenant_id TEXT NOT NULL,
    user_id TEXT NOT NULL,
    app_id TEXT NOT NULL,
    ingress_id TEXT NOT NULL,
    suspended_at TIMESTAMPTZ DEFAULT now() NOT NULL,
    suspended_revision BIGINT,
    CONSTRAINT quota_suspensions_pkey PRIMARY KEY (tenant_id, user_id, app_id, ingress_id),
    CONSTRAINT quota_suspensions_tenant_id_user_id_fkey FOREIGN KEY (tenant_id, user_id) REFERENCES users(tenant_id, id) ON DELETE CASCADE
);

-- One chain's landing on one machine: what it accepts and where it forwards.
--
-- The relay port hangs here rather than on the node because each chain has its own inbound. One
-- inbound cannot accept both cleartext and encrypted traffic, and one relay may perfectly well serve
-- two chains on their own transport layers — one taking REALITY through censorship, the other
-- unencrypted on a datacenter network for speed. On the node the model has only one place to hold it
-- and that topology becomes inexpressible.
--
-- The listening port and wire format are `hop_in_port` / `hop_in_wire`, and which address to
-- dial is written on the chain's forward rule (`rules[].a.dial`).
--
-- Putting addresses on the chain has a cost. A machine's public address is written once per chain,
-- and changing an IP means editing N chains. It was chosen deliberately — what it buys is that which
-- network a hop takes is entirely the chain's to say, with no need for the compiler to guess which
-- pairs of machines have direct internal reachability (the symptom of guessing wrong being traffic
-- quietly taking a different path while the artifacts look entirely correct).
--
-- hop_in_wire is stored as jsonb rather than split into columns: the variants carry entirely
-- different material (none carries nothing, encryption an X25519 pair, reality keys plus dest plus
-- serverNames plus shortIds), and split into columns that is a pile of fields non-null under one
-- variant each, with no constraint expressible over them. The same reason rules is jsonb, and the
-- shape is defined by `brocade_core::model::HopWire`'s serde.
--
-- The port column being nullable merely means the database layer does not enforce it; the write path
-- never writes null: `brocade_core::model::HopIn::port` is required, the UI picks a free port when a
-- chain is created, and nobody has to care what it is. The port lives in the model rather than being
-- recomputed by the compiler each time because it must be stable — any change means an altered xray
-- config, a process restart, and every connection on that machine dropping, whereas recomputed,
-- somebody adding a chain could push it onto another port and cause a silent restart.
CREATE TABLE IF NOT EXISTS steps (
    chain_id TEXT NOT NULL,
    node_id TEXT NOT NULL,
    accept_uuid UUID,
    accept_label TEXT,
    rules JSONB DEFAULT '[]'::jsonb NOT NULL,
    created_at TIMESTAMPTZ DEFAULT now() NOT NULL,
    created_revision BIGINT,
    hop_in_port INTEGER,
    hop_in_wire JSONB,
    CONSTRAINT steps_check CHECK ((((accept_uuid IS NULL) AND (accept_label IS NULL)) OR ((accept_uuid IS NOT NULL) AND (accept_label IS NOT NULL)))),
    CONSTRAINT steps_hop_in_check CHECK ((((hop_in_port IS NULL) AND (hop_in_wire IS NULL)) OR ((hop_in_wire IS NOT NULL) AND ((hop_in_port IS NULL) OR ((hop_in_port >= 1) AND (hop_in_port <= 65535)))))),
    CONSTRAINT steps_rules_check CHECK ((jsonb_typeof(rules) = 'array')),
    CONSTRAINT steps_pkey PRIMARY KEY (chain_id, node_id),
    CONSTRAINT steps_chain_id_fkey FOREIGN KEY (chain_id) REFERENCES chains(id) ON DELETE CASCADE,
    CONSTRAINT steps_created_revision_fkey FOREIGN KEY (created_revision) REFERENCES revisions(id),
    CONSTRAINT steps_node_id_fkey FOREIGN KEY (node_id) REFERENCES nodes(id) ON DELETE RESTRICT
);

-- Link-hop usage.
--
-- The convention is exactly one counting point per hop. For every hop on a relay chain but the
-- ingress, that point is Step.accept.label (`{chain}@{node}`) — xray emits a `user>>>{label}` counter
-- for it as usual, except that this family of labels has no per-user dimension.
--
-- An exit machine's bandwidth cost must be booked separately: the bytes are the same batch as the
-- user's and the resources are not — that 1 GB crossed the ingress machine's NIC once and the exit
-- machine's NIC once, and two machines each paid for bandwidth.
--
-- Its own table rather than allowing NULL in usage_samples' user_id. Allowed,
-- `SELECT sum(downlink_bytes) FROM usage_samples WHERE tenant_id = $1` would silently put link
-- overhead on a user's bill, and nothing anywhere would report that error. Split into two tables,
-- that mistaken query cannot be written at all — the same technique as leaving ObservedClient
-- structurally without a level.
CREATE TABLE IF NOT EXISTS usage_chain_samples (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    sampled_at TIMESTAMPTZ DEFAULT now() NOT NULL,
    window_start TIMESTAMPTZ NOT NULL,
    window_end TIMESTAMPTZ NOT NULL,
    node_id TEXT NOT NULL,
    tenant_id TEXT NOT NULL,
    app_id TEXT NOT NULL,
    chain_id TEXT NOT NULL,
    hop_label TEXT NOT NULL,
    uplink_bytes BIGINT NOT NULL,
    downlink_bytes BIGINT NOT NULL,
    has_gap BOOLEAN DEFAULT false NOT NULL,
    revision_id BIGINT,
    deployment_id BIGINT,
    CONSTRAINT usage_chain_samples_check CHECK ((window_end > window_start)),
    CONSTRAINT usage_chain_samples_downlink_bytes_check CHECK ((downlink_bytes >= 0)),
    CONSTRAINT usage_chain_samples_uplink_bytes_check CHECK ((uplink_bytes >= 0)),
    CONSTRAINT usage_chain_samples_node_id_hop_label_window_start_window_e_key UNIQUE (node_id, hop_label, window_start, window_end),
    CONSTRAINT usage_chain_samples_pkey PRIMARY KEY (id),
    CONSTRAINT usage_chain_samples_deployment_id_fkey FOREIGN KEY (deployment_id) REFERENCES deployments(id),
    CONSTRAINT usage_chain_samples_node_id_fkey FOREIGN KEY (node_id) REFERENCES nodes(id) ON DELETE RESTRICT,
    CONSTRAINT usage_chain_samples_revision_id_fkey FOREIGN KEY (revision_id) REFERENCES revisions(id),
    CONSTRAINT usage_chain_samples_tenant_id_fkey FOREIGN KEY (tenant_id) REFERENCES tenants(id) ON DELETE RESTRICT
);

