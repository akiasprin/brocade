/// The share link's `extra`, put back through the binary that has to read it.
///
/// The connection pool has exactly one way into an XHTTP share link: `extra`, whose contents
/// xray does not merge but *substitutes* — `SplitHTTPConfig::Build` unmarshals it into a fresh
/// config, copies `host`, `path` and `mode` back onto it and then keeps the new one. So the
/// question a unit test cannot answer is whether the block we emit survives that, and whether it
/// is read at all: an unknown key inside `xhttpSettings` would pass `-test` in silence, and the
/// setting would be gone without a word.
///
/// The second half is what makes this a check rather than a formality. A concurrency xray must
/// refuse has to actually be refused; if it passes, `extra` is being ignored and the first
/// assertion proved nothing.
#[test]
fn the_share_link_extra_carries_the_pool_into_a_config_the_real_binary_reads() {
    let Some(binary) = xray_binary() else {
        eprintln!("跳过：没找到 xray 二进制（设 BROCADE_XRAY_BIN 或放到 .tools/xray）");
        return;
    };

    let (doc, mut app) = base_model(HopDial::Overlay, HopWire::None);
    app.ingresses[0].wires = IngressWires::Vless(Transport::VlessRealityXhttp(RealityXhttp {
        reality: app.ingresses[0].wires.reality().unwrap().clone(),
        xhttp: Xhttp {
            path: "/pool".to_owned(),
            host: None,
            // One: a connection per stream, reused once it goes idle. The whole point of the
            // exercise, and the value that used to reach no client at all.
            xmux: Some(XhttpXmux::with_concurrency(1)),
            tuning: None,
            mode: XhttpMode::Auto,
        },
    }));
    app.ingresses[0].wires.set_flow(None);
    app.grants.push(brocade_core::model::Grant {
        tenant: "platform".to_owned(),
        user: "alice".to_owned(),
        ingress: "i-relay".to_owned(),
    });

    let mut diagnostics = Vec::new();
    let app_ir = compile_app(&doc, &app, &mut diagnostics);
    assert!(
        diagnostics.iter().all(|d| d.level != Level::Error),
        "{diagnostics:#?}"
    );
    let uri_text = uri::subscription(&subscription::build(&project_user(
        &[app_ir],
        "platform",
        "alice",
    )));

    let extra = share_link_extra(&uri_text);
    assert_eq!(
        extra,
        json!({
            "xmux": {
                "maxConcurrency": 1,
                "hMaxRequestTimes": "600-900",
                "hMaxReusableSecs": "1800-3000"
            }
        }),
        "{uri_text}"
    );

    assert!(
        client_config_loads(&binary, "pool", &extra),
        "带 extra 的客户端配置 xray 不认：{extra}"
    );
    assert!(
        !client_config_loads(
            &binary,
            "pool-negative",
            &json!({ "xmux": { "maxConcurrency": "十六" } })
        ),
        "xray 收下了一个非法并发，说明它根本没在读 extra——上面那条断言什么也没证明"
    );
}

/// The value of the `extra` query parameter, decoded. Panics rather than returning an option:
/// every caller here has just asserted the link should carry one.
fn share_link_extra(uri_text: &str) -> Value {
    let raw = uri_text
        .split(['?', '&'])
        .find_map(|pair| pair.strip_prefix("extra="))
        .unwrap_or_else(|| panic!("链接里没有 extra：{uri_text}"))
        .split('#')
        .next()
        .unwrap();
    let mut bytes = Vec::new();
    let mut chars = raw.chars();
    while let Some(c) = chars.next() {
        if c == '%' {
            let hex: String = chars.by_ref().take(2).collect();
            bytes.push(u8::from_str_radix(&hex, 16).unwrap());
        } else {
            bytes.push(c as u8);
        }
    }
    serde_json::from_slice(&bytes).unwrap()
}

/// Does xray build a client outbound out of this `extra`? The shape around it is the one a
/// share link importer writes: `extra` sits inside `xhttpSettings`, beside the three keys the
/// substitution copies back.
fn client_config_loads(binary: &std::path::Path, name: &str, extra: &Value) -> bool {
    let config = serde_json::to_string_pretty(&json!({
        "outbounds": [{
            "protocol": "vless",
            "settings": { "vnext": [{
                "address": "hk.example.net",
                "port": 443,
                "users": [{ "id": "6f9d1a8e-2b3c-4d5e-8f70-1a2b3c4d5e6f", "encryption": "none" }],
            }]},
            "streamSettings": {
                "network": "xhttp",
                "security": "reality",
                "realitySettings": {
                    "serverName": "apps.apple.com",
                    "fingerprint": "chrome",
                    "publicKey": INGRESS_PUBLIC,
                    "shortId": "abcdef0123456789",
                },
                "xhttpSettings": { "path": "/pool", "extra": extra },
            },
        }],
    }))
    .unwrap();
    let path = std::env::temp_dir().join(format!("brocade-xray-extra-{name}.json"));
    fs::write(&path, &config).unwrap();
    let output = Command::new(binary)
        .args(["-test", "-c"])
        .arg(&path)
        .output()
        .expect("跑不起来 xray");
    let _ = fs::remove_file(&path);
    String::from_utf8_lossy(&output.stdout).contains("Configuration OK")
}

