//! Validating the generated artifacts against a real xray.
//!
//! Unit tests can only prove that we rendered the fields we believe to be right; they cannot
//! prove xray accepts them. This change gave relay ports a transport layer, and the syntax
//! of those `decryption` / `encryption` strings was copied from `xray vlessenc`, where one
//! mistyped dot means every relay machine fails to start — which only becomes visible after
//! a release.
//!
//! Skipped when no xray binary is available: it is an external tool and should not be a hard
//! dependency of `cargo test`. The path comes from `BROCADE_XRAY_BIN`, falling back to
//! `.tools/xray` at the workspace root (already gitignored).

