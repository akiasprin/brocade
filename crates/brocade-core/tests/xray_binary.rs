/// An XHTTP ingress, checked against the real binary.
///
/// Worth its own case because this is exactly the pair xray's own `-test` cannot judge. It
/// answers `Configuration OK` to an XHTTP ingress carrying Vision — a combination the running
/// server then refuses on every connection — so the compiler is what has to refuse it, and this
/// test guards the other half: that what the compiler *does* emit is something xray accepts.
#[test]
fn an_xhttp_ingress_loads_in_the_real_binary() {
    let Some(binary) = xray_binary() else {
        eprintln!("跳过：没找到 xray 二进制（设 BROCADE_XRAY_BIN 或放到 .tools/xray）");
        return;
    };

    // Every mode string is here for a reason beyond coverage: xray refuses an unknown one at
    // build time (`unsupported mode: …`), so this is what checks our spellings against the
    // binary rather than against a doc page.
    for (name, mux, mode) in [
        ("xhttp-plain", None, XhttpMode::Auto),
        ("xhttp-mux", Some(16u16), XhttpMode::Auto),
        ("xhttp-packet-up", None, XhttpMode::PacketUp),
        ("xhttp-stream-up", None, XhttpMode::StreamUp),
        ("xhttp-stream-one", None, XhttpMode::StreamOne),
    ] {
        let (doc, mut app) = base_model(HopDial::Overlay, HopWire::None);
        app.ingresses[0].wires = IngressWires::Vless(Transport::VlessRealityXhttp(RealityXhttp {
            reality: app.ingresses[0].wires.reality().unwrap().clone(),
            xhttp: Xhttp {
                path: "/probe".to_owned(),
                host: None,
                xmux: mux.map(XhttpXmux::with_concurrency),
                tuning: None,
                mode,
            },
        }));
        // Vision is the default and cannot ride XHTTP; the compiler refuses the pair, so the
        // model reaching xray always has it off.
        app.ingresses[0].wires.set_flow(None);

        let mut diagnostics = Vec::new();
        let sys = compile_system(&doc, &mut diagnostics);
        let app_ir = compile_hops(
            compile_app(&doc, &app, &mut diagnostics),
            &sys,
            &mut diagnostics,
        );
        assert!(
            diagnostics.iter().all(|d| d.level != Level::Error),
            "{diagnostics:#?}"
        );

        let config = json::xray(&xray::build(&project_node(
            &sys,
            std::slice::from_ref(&app_ir),
            "hk",
        )));
        let value: Value = serde_json::from_str(&config).unwrap();
        let subscriber = value["inbounds"]
            .as_array()
            .unwrap()
            .iter()
            .find(|inbound| inbound["tag"] == "in:relay/i-relay")
            .expect("subscriber XHTTP inbound");
        assert_eq!(
            subscriber["streamSettings"]["sockopt"]["tcpFastOpen"], 256,
            "XHTTP subscriber listener must enable TFO: {subscriber:#?}"
        );
        assert!(
            config.contains("\"network\": \"xhttp\"") && config.contains("\"path\": \"/probe\""),
            "产物里没有 xhttp 的痕迹：\n{config}"
        );
        match mode.as_str() {
            Some(spelling) => assert!(
                config.contains(&format!("\"mode\": \"{spelling}\"")),
                "产物里没写上行姿势 {spelling}：\n{config}"
            ),
            // The default is written nowhere: a server that names a mode refuses every client
            // naming another, so an unasked-for value would lock out subscriptions already issued.
            None => assert!(
                !config.contains("\"mode\""),
                "没人选的时候不该写 mode：\n{config}"
            ),
        }

        let path = std::env::temp_dir().join(format!("brocade-xray-{name}.json"));
        fs::write(&path, &config).unwrap();
        let output = Command::new(&binary)
            .args(["-test", "-c"])
            .arg(&path)
            .output()
            .expect("跑不起来 xray");
        let stdout = String::from_utf8_lossy(&output.stdout);
        assert!(
            stdout.contains("Configuration OK"),
            "{name} 的产物 xray 不认：\n{stdout}\n{}\n----\n{config}",
            String::from_utf8_lossy(&output.stderr)
        );
        let _ = fs::remove_file(&path);
    }
}

